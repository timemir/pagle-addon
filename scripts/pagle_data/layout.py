"""The real-font layout harness's Python half (scripts/measure-layout.sh): the advance widths its Lua half measures
with, the report of what it found against the allowlist, and the PNGs of the stops it found something on.

- `advances_lua(fonts)`: every bundled face's advance widths at 1000 units an em, for a fixed set of characters
  (Latin, Latin-1 and Extended-A and -B, Cyrillic, the punctuation the locales use), and its line height (ascent
  plus descent), as the Lua table scripts/measure-layout/advances.lua. A Cyrillic letter a face lacks gets its Latin
  look-alike's width, marked estimated; any other glyph a face lacks is left out (the Lua half guesses half an em).
- `load_allowlist(path)`: the accepted findings, each with its reason (scripts/measure-layout/allowlist.toml).
- `report(findings, allowlist)`: the findings grouped by what they are, each new or allowed, as text lines.
- `draw(stop_file, png, fonts)`: one stop's surfaces, its texts in their real faces, each finding outlined.
"""

from __future__ import annotations

import fnmatch
import json
import tomllib
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from PIL import Image, ImageDraw, ImageFont

FONTS_DIR = Path("addons/Pagle/media/fonts")
ADVANCES_LUA = Path("scripts/measure-layout/advances.lua")
KINDS = ("cut", "out", "overlap")

# The characters measured: printable ASCII, Latin-1, Latin Extended-A and -B, Cyrillic, general punctuation (dashes,
# quotes, bullet, ellipsis), the euro sign, arrows and the minus sign.
RANGES = ((0x20, 0x7E), (0xA0, 0x24F), (0x400, 0x45F), (0x2010, 0x203A), (0x20AC, 0x20AC), (0x2190, 0x2193),
          (0x2212, 0x2212))

# Each Cyrillic letter's Latin look-alike, for its width in a face without Cyrillic: an estimate.
CYRILLIC_LOOKALIKES = dict(zip(
    "АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯабвгдежзийклмнопрстуфхцчшщъыьэюяЁё",
    "ABBFDEWBNNKNMHOHPCTYOXUUWWBMBCWRabbrdeweuuknmnonpcmyoxuuwwbmbewaEe",
    strict=True,
))


def face_advances(path: Path) -> tuple[dict[int, int], set[int], float]:
    """One face's advance per codepoint at 1000 units an em, the codepoints estimated, and its line height in ems."""
    font = ImageFont.truetype(str(path), 1000)
    # Whether the face has a glyph: unlike the notdef glyph, in advance or ink box (at a small size, which is quick).
    probe = ImageFont.truetype(str(path), 48)
    notdef = (probe.getlength("\uffff"), probe.getbbox("\uffff"))

    def has(char: str) -> bool:
        return char == " " or (probe.getlength(char), probe.getbbox(char)) != notdef

    advances: dict[int, int] = {}
    estimated: set[int] = set()
    for low, high in RANGES:
        for code in range(low, high + 1):
            char = chr(code)
            if has(char):
                advances[code] = round(font.getlength(char))
            elif char in CYRILLIC_LOOKALIKES and has(CYRILLIC_LOOKALIKES[char]):
                advances[code] = round(font.getlength(CYRILLIC_LOOKALIKES[char]))
                estimated.add(code)
    ascent, descent = font.getmetrics()
    return advances, estimated, (ascent + descent) / 1000


def advances_lua(fonts: Path) -> str:
    """scripts/measure-layout/advances.lua's text: every face under `fonts`, by file name."""
    out = [
        "-- Generated by `.tools/bin/python scripts/measure-layout.py advances` from addons/Pagle/media/fonts/*.ttf:",
        "-- each face's advance width per codepoint at 1000 units an em, the codepoints estimated from a Latin",
        "-- look-alike, and its line height in ems (ascent plus descent). Don't edit; scripts/measure-layout.sh and",
        "-- scripts/tests/test_layout.py check it's current.",
        "return {",
        "\tfaces = {",
    ]
    for path in sorted(fonts.glob("*.ttf")):
        advances, estimated, line = face_advances(path)
        out.append(f'\t\t["{path.name}"] = {{')
        out.append(f"\t\t\tline = {line:.3f},")
        out.append("\t\t\tadvances = {")
        codes = sorted(advances)
        for i in range(0, len(codes), 12):
            out.append("\t\t\t\t" + " ".join(f"[{c}] = {advances[c]}," for c in codes[i:i + 12]))
        out.append("\t\t\t},")
        out.append("\t\t\testimated = {")
        marked = sorted(estimated)
        for i in range(0, len(marked), 12):
            out.append("\t\t\t\t" + " ".join(f"[{c}] = true," for c in marked[i:i + 12]))
        out.append("\t\t\t},")
        out.append("\t\t},")
    out += ["\t},", "}", ""]
    return "\n".join(out)


@dataclass(frozen=True)
class Allow:
    """One accepted finding: what it matches (globs, as fnmatch reads them) and why it's accepted."""

    kind: str
    text: str
    reason: str
    other: str | None = None
    stop: str | None = None
    detail: str | None = None
    languages: tuple[str, ...] = ()

    def matches(self, finding: dict[str, Any], language: str) -> bool:
        return (finding["kind"] == self.kind
                and fnmatch.fnmatchcase(finding["text"], self.text)
                and (self.other is None or fnmatch.fnmatchcase(finding.get("other") or "", self.other))
                and (self.stop is None or fnmatch.fnmatchcase(finding["stop"], self.stop))
                and (self.detail is None or fnmatch.fnmatchcase(finding["detail"], self.detail))
                and (not self.languages or language in self.languages))


def load_allowlist(path: Path) -> list[Allow]:
    """The allowlist's entries; a ValueError names the first one that's malformed."""
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    entries: list[Allow] = []
    known = {"kind", "text", "reason", "other", "stop", "detail", "languages"}
    for n, entry in enumerate(data.get("allow", []), start=1):
        where = f"{path}: allow #{n}"
        if unknown := set(entry) - known:
            raise ValueError(f"{where} has unknown keys {sorted(unknown)}")
        if entry.get("kind") not in KINDS:
            raise ValueError(f"{where}: kind must be one of {', '.join(KINDS)}")
        if not isinstance(entry.get("text"), str) or not entry["text"]:
            raise ValueError(f"{where} needs a text")
        if not isinstance(entry.get("reason"), str) or not entry["reason"].strip():
            raise ValueError(f"{where} needs a reason")
        languages = entry.get("languages", [])
        if isinstance(languages, str):
            languages = [languages]
        for key in ("other", "stop", "detail"):
            if key in entry and not isinstance(entry[key], str):
                raise ValueError(f"{where}: {key} must be a string")
        if not all(isinstance(language, str) for language in languages):
            raise ValueError(f"{where}: languages must be strings")
        entries.append(Allow(entry["kind"], entry["text"], entry["reason"].strip(), entry.get("other"),
                             entry.get("stop"), entry.get("detail"), tuple(languages)))
    return entries


def read_findings(path: Path) -> list[dict[str, Any]]:
    """The Lua half's findings.jsonl."""
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


@dataclass
class Group:
    """One finding as it repeats across stops: the stops it's on and the first one's detail."""

    kind: str
    text: str
    other: str | None
    detail: str
    estimated: bool
    allow: Allow | None
    stops: list[str] = field(default_factory=list)
    files: set[str] = field(default_factory=set)


def group(findings: Iterable[dict[str, Any]], allowlist: Sequence[Allow], language: str) -> list[Group]:
    """The findings grouped by kind, text and the text they meet, in the order first found."""
    groups: dict[tuple[str, str, str | None], Group] = {}
    for finding in findings:
        key = (finding["kind"], finding["text"], finding.get("other"))
        allow = next((a for a in allowlist if a.matches(finding, language)), None)
        g = groups.get(key)
        if g is None:
            g = groups[key] = Group(finding["kind"], finding["text"], finding.get("other"), finding["detail"],
                                    bool(finding.get("estimated")), allow)
        elif g.allow is not None and allow is None:
            g.allow = None  # a stop the allowlist doesn't cover makes the whole group new
        if finding["stop"] not in g.stops:
            g.stops.append(finding["stop"])
        g.files.add(finding["file"])
    return list(groups.values())


def _one_line(text: str) -> str:
    return text.replace("\n", "\\n")


def report(groups: Sequence[Group], language: str, verbose: bool = False) -> list[str]:
    """The report's lines: each new finding with its stops, then a count of the allowed ones (each, if verbose)."""
    new = [g for g in groups if g.allow is None]
    allowed = [g for g in groups if g.allow is not None]
    lines: list[str] = []
    for g in new + (allowed if verbose else []):
        tag = "NEW    " if g.allow is None else "allowed"
        met = f' meets "{_one_line(g.other)}"' if g.other else ""
        est = " (estimated)" if g.estimated else ""
        stops = ", ".join(g.stops[:3]) + (f" and {len(g.stops) - 3} more" if len(g.stops) > 3 else "")
        lines.append(f'{language} {tag} {g.kind:<7} "{_one_line(g.text)}"{met}{est}')
        lines.append(f"        {g.detail}; at {stops}")
        if g.allow is not None:
            lines.append(f"        allowed: {g.allow.reason}")
    lines.append(f"{language}: {len(new)} new finding{'' if len(new) == 1 else 's'}, {len(allowed)} allowed")
    return lines


# --- PNGs

SCALE = 2.0
PAPER = (243, 229, 195)
NEW_RED = (220, 0, 0)
ALLOWED_AMBER = (230, 150, 0)
CYRILLIC_FACE = "Caveat-Medium.ttf"  # the one bundled face with Cyrillic, to draw ruRU text the stand-in lacks


class _Faces:
    def __init__(self, fonts: Path) -> None:
        self.fonts = fonts
        self.cache: dict[tuple[str, float], ImageFont.FreeTypeFont] = {}

    def get(self, file: str, size: float, text: str) -> ImageFont.FreeTypeFont:
        if any("Ѐ" <= c <= "џ" for c in text) and file != CYRILLIC_FACE:
            font = self.get(file, size, "")
            if font.getlength("Ж") == font.getlength("￿"):
                file = CYRILLIC_FACE
        key = (file, size)
        if key not in self.cache:
            self.cache[key] = ImageFont.truetype(str(self.fonts / file), max(1, round(size * SCALE)))
        return self.cache[key]


def draw(stop_file: Path, png: Path, fonts: Path, marks: dict[str, tuple[int, int, int]]) -> None:
    """Draws the surfaces of one stop that hold a marked text (`marks`: text to outline colour), cropped to them:
    frames outlined, colour textures filled, texts in their faces, each marked text's ink outlined."""
    lines = stop_file.read_text(encoding="utf-8").splitlines()
    head = json.loads(lines[0])
    records = [json.loads(line) for line in lines[1:]]
    shown = {r["surface"] for r in records if r.get("text") in marks} or {r["surface"] for r in records}
    records = [r for r in records if r["surface"] in shown]
    if not records:
        return
    x0 = min(r["rect"][0] for r in records) - 10
    y0 = min(r["rect"][1] for r in records) - 30
    x1 = max(r["rect"][2] for r in records) + 10
    y1 = max(r["rect"][3] for r in records) + 10
    x0, y0, x1, y1 = max(x0, -50), max(y0, -50), min(x1, 1970), min(y1, 1130)
    image = Image.new("RGB", (int((x1 - x0) * SCALE), int((y1 - y0) * SCALE)), PAPER)
    pen = ImageDraw.Draw(image)

    def at(x: float, y: float) -> tuple[float, float]:
        return (x - x0) * SCALE, (y - y0) * SCALE

    pen.text((4, 4), f"{head['language']} {head['index']:02d} {head['stop']}", fill=(0, 0, 0))
    for r in records:
        left, top, right, bottom = r["rect"]
        if right - left <= 0 or bottom - top <= 0 or r["kind"] == "FontString":
            continue
        if r["kind"] == "Texture" and r.get("color") and (right - left) * (bottom - top) < 2000:
            colour = tuple(int(max(0.0, min(1.0, v or 0)) * 255) for v in r["color"][:3])
            pen.rectangle([at(left, top), at(right, bottom)], fill=colour)
        elif r["kind"] != "Texture":
            pen.rectangle([at(left, top), at(right, bottom)], outline=(200, 185, 150))
    faces = _Faces(fonts)
    for r in records:
        if r["kind"] != "FontString":
            continue
        left, top, right, bottom = r["ink"] or r["rect"]
        font = faces.get(r["font"], r["size"], r["text"])
        colour = tuple(int(max(0.0, min(1.0, v)) * 255) for v in r["color"])
        if sum(colour) > 600:  # light text on a dark ground the PNG doesn't draw
            colour = (90, 60, 30)
        for i, text in enumerate(r["lines"]):
            width = font.getlength(text) / SCALE
            if r["cut"] and width > right - left + 0.5:
                while text and font.getlength(text + "…") / SCALE > right - left:
                    text = text[:-1]
                text += "…"
                width = font.getlength(text) / SCALE
            x = (left if r["justify"] == "LEFT" else right - width if r["justify"] == "RIGHT"
                 else (left + right - width) / 2)
            pen.text(at(x, top + i * r["line"]), text, font=font, fill=colour)
        mark = marks.get(r["text"])
        if mark:
            pen.rectangle([at(left, top), at(right, bottom)], outline=mark, width=2)
    png.parent.mkdir(parents=True, exist_ok=True)
    image.save(png)


def draw_findings(out: Path, groups: Sequence[Group], fonts: Path, every_stop: bool = False) -> list[Path]:
    """A PNG per stop with a finding (or every stop), under out/png/: new findings outlined red, allowed amber."""
    marks: dict[str, dict[str, tuple[int, int, int]]] = {}
    for g in groups:
        for file in g.files:
            colour = NEW_RED if g.allow is None else ALLOWED_AMBER
            texts = marks.setdefault(file, {})
            for text in (g.text, g.other):
                if text and texts.get(text) != NEW_RED:
                    texts[text] = colour
    files = sorted(p.name for p in out.glob("[0-9]*.jsonl")) if every_stop else sorted(marks)
    written = []
    for file in files:
        png = out / "png" / (Path(file).stem + ".png")
        draw(out / file, png, fonts, marks.get(file, {}))
        written.append(png)
    return written
