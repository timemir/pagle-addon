"""The pages behind a variety's name (#582, VAR-R28): how light each toast style's page is where the name line stands,
on its toast, ruled and gilt pages and its Nod, measured from the BLP art, for adapter/Art.lua to pick the ink that
reads best there (ns.VarietyNameInk).

scripts/measure-name-pages/probe.lua draws every style's pages under busted with the layout harness's helper (HELPER:
every font string in its real face, a font object given by name resolved as the client resolves it, #620) and writes,
for each, the band the name line takes and the textures drawn under the words there. This module composites those
textures from the BLPs, measures the band's mean WCAG relative luminance (each pixel weighted by its alpha: what shows
through the page is the world's, not the page's), and writes the generated NAME_PAGES block in adapter/Art.lua, or
checks it.

- `measure(records, addons)`: each style's luminance by page.
- `lua_block(pages)`: the generated block's text.
- `replace_block(text, block)` / `read_block(text)`: the block in Art.lua's text.
- `differences(old, new)`: where a committed table and the art disagree.
"""

import json
import re
from collections.abc import Iterable, Sequence
from pathlib import Path
from typing import Any

from PIL import Image, ImageChops, ImageOps

ART_LUA = Path("addons/Pagle/adapter/Art.lua")
PROBE = Path("scripts/measure-name-pages/probe.lua")
HELPER = Path("scripts/measure-layout/helper.lua")
BEGIN = "-- BEGIN NAME_PAGES (generated by scripts/measure-name-pages.py; don't edit by hand)"
END = "-- END NAME_PAGES"
PAGES = ("toast", "toast-ruled", "high", "nod")
# Pixels per UI unit the band is composited at.
SCALE = 2
# How far a committed luminance may stand from the art's before the check fails: the last digit written, and what
# a resampler's rounding can move.
TOLERANCE = 0.002
LAYERS = {"BACKGROUND": 0, "BORDER": 1, "ARTWORK": 2, "OVERLAY": 3, "HIGHLIGHT": 4}


def linear(channel: float) -> float:
    """An sRGB channel, 0 to 1, made linear (WCAG 2)."""
    return channel / 12.92 if channel <= 0.03928 else ((channel + 0.055) / 1.055) ** 2.4


def relative_luminance(rgb: Sequence[float]) -> float:
    """An { r, g, b } colour's WCAG relative luminance, each channel 0 to 1."""
    return 0.2126 * linear(rgb[0]) + 0.7152 * linear(rgb[1]) + 0.0722 * linear(rgb[2])


def contrast(a: float, b: float) -> float:
    """WCAG's contrast ratio of two relative luminances."""
    return (max(a, b) + 0.05) / (min(a, b) + 0.05)


def read_records(path: Path) -> list[dict[str, Any]]:
    """The probe's records, one a line."""
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


class Art:
    """The BLPs under `addons`, each opened once, by the client's texture path (Interface\\AddOns\\...)."""

    def __init__(self, addons: Path) -> None:
        self.addons = addons
        self.images: dict[str, Image.Image] = {}

    def get(self, texture: str) -> Image.Image:
        if texture not in self.images:
            relative = texture.split("AddOns\\", 1)[1].replace("\\", "/")
            path = self.addons / (relative + ".blp")
            if not path.exists():
                raise FileNotFoundError(f"name pages: no art {path} for {texture}")
            self.images[texture] = Image.open(path).convert("RGBA")
        return self.images[texture]


def _sprite(art: Art, texture: dict[str, Any], width: int, height: int) -> Image.Image:
    """One texture as drawn: its atlas cut by its coordinates, sized, tinted (greyed first when desaturated) and faded."""
    if texture.get("tex"):
        atlas = art.get(texture["tex"])
        tc = texture.get("tc") or [0, 1, 0, 1]
        if len(tc) == 8:
            u1, u2, v1, v2 = tc[0], tc[4], tc[1], tc[3]
        else:
            u1, u2, v1, v2 = tc
        w, h = atlas.size
        box = (round(min(u1, u2) * w), round(min(v1, v2) * h), round(max(u1, u2) * w), round(max(v1, v2) * h))
        if box[2] - box[0] < 1 or box[3] - box[1] < 1:
            return Image.new("RGBA", (width, height), (0, 0, 0, 0))
        sprite = atlas.crop(box)
        if u1 > u2:
            sprite = ImageOps.mirror(sprite)
        if v1 > v2:
            sprite = ImageOps.flip(sprite)
        sprite = sprite.resize((width, height), Image.Resampling.LANCZOS)
    else:
        colour = texture["color"]
        alpha = colour[3] if len(colour) > 3 else 1
        sprite = Image.new("RGBA", (width, height),
                           tuple(round(c * 255) for c in colour[:3]) + (round(alpha * 255),))
    tint = texture.get("vc")
    alpha_channel = sprite.getchannel("A")
    rgb = sprite.convert("RGB")
    if texture.get("desaturated"):
        grey = ImageOps.grayscale(rgb)
        rgb = Image.merge("RGB", (grey, grey, grey))
    if tint and any(abs(v - 1) > 1e-3 for v in tint[:3]):
        rgb = Image.merge("RGB", [band.point(lambda v, m=tint[i]: round(v * m)) for i, band in enumerate(rgb.split())])
    faded = float(texture.get("alpha", 1)) * (float(tint[3]) if tint and len(tint) > 3 and tint[3] is not None else 1)
    if faded < 1:
        alpha_channel = alpha_channel.point(lambda v: round(v * faded))
    out = rgb.convert("RGBA")
    out.putalpha(alpha_channel)
    return out


def composite(art: Art, record: dict[str, Any]) -> Image.Image:
    """The band of one record, its textures drawn in the client's order (frame level, layer, sublevel, then as held)."""
    left, top, right, bottom = record["band"]
    canvas = Image.new("RGBA", (max(1, round((right - left) * SCALE)), max(1, round((bottom - top) * SCALE))),
                       (0, 0, 0, 0))
    ordered = sorted(enumerate(record["textures"]),
                     key=lambda t: (t[1].get("fl") or 0, LAYERS.get(t[1].get("layer"), 2), t[1].get("sub") or 0, t[0]))
    for _, texture in ordered:
        x1, y1, x2, y2 = texture["rect"]
        if x2 <= left or x1 >= right or y2 <= top or y1 >= bottom:
            continue
        width, height = round((x2 - x1) * SCALE), round((y2 - y1) * SCALE)
        if width < 1 or height < 1:
            continue
        sprite = _sprite(art, texture, width, height)
        # The part of the sprite inside the band, and where it lands.
        ox, oy = round((x1 - left) * SCALE), round((y1 - top) * SCALE)
        cx1, cy1 = max(0, -ox), max(0, -oy)
        cx2, cy2 = min(width, canvas.width - ox), min(height, canvas.height - oy)
        if cx2 <= cx1 or cy2 <= cy1:
            continue
        part = sprite.crop((cx1, cy1, cx2, cy2))
        at = (ox + cx1, oy + cy1)
        if texture.get("blend") == "ADD":
            under = canvas.crop((at[0], at[1], at[0] + part.width, at[1] + part.height))
            weight = part.getchannel("A")
            added = Image.merge("RGB", [ImageChops.multiply(c, weight) for c in part.convert("RGB").split()])
            lit = ImageChops.add(under.convert("RGB"), added).convert("RGBA")
            lit.putalpha(under.getchannel("A"))
            canvas.paste(lit, at)
        else:
            canvas.alpha_composite(part, at)
    return canvas


def mean_luminance(image: Image.Image) -> float:
    """The mean relative luminance of `image`'s pixels, each weighted by its alpha."""
    table = [linear(v / 255) for v in range(256)]
    total = weight = 0.0
    data = image.convert("RGBA").tobytes()
    for i in range(0, len(data), 4):
        r, g, b, a = data[i], data[i + 1], data[i + 2], data[i + 3]
        if a:
            total += a * (0.2126 * table[r] + 0.7152 * table[g] + 0.0722 * table[b])
            weight += a
    if weight == 0:
        raise ValueError("name pages: nothing drawn behind the name line")
    return total / weight


def measure(records: Iterable[dict[str, Any]], addons: Path) -> dict[str, dict[str, float]]:
    """Each style's page luminance behind the name line, by page, rounded to 3 places."""
    art = Art(addons)
    pages: dict[str, dict[str, float]] = {}
    for record in records:
        pages.setdefault(record["style"], {})[record["page"]] = round(mean_luminance(composite(art, record)), 3)
    return pages


def _key(page: str) -> str:
    return page if re.fullmatch(r"[a-z]+", page) else f'["{page}"]'


def lua_block(pages: dict[str, dict[str, float]]) -> str:
    """The generated block: NAME_PAGES, by style ID, each page's luminance."""
    lines = [
        BEGIN,
        "-- Each toast style's page behind the name line (the WCAG relative luminance of its mean, the art composited",
        "-- where the line stands), on the toast, ruled and gilt pages and the Nod (#582, VAR-R28).",
        "---@type table<string, table<string, number>>",
        "local NAME_PAGES = {",
    ]
    for style in sorted(pages):
        values = ", ".join(f"{_key(page)} = {pages[style][page]:.3f}" for page in PAGES if page in pages[style])
        lines.append(f'\t["{style}"] = {{ {values} }},')
    lines += ["}", END]
    return "\n".join(lines)


def replace_block(text: str, block: str) -> str:
    """`text` with its generated block replaced by `block`."""
    start, end = text.index(BEGIN), text.index(END) + len(END)
    return text[:start] + block + text[end:]


def read_block(text: str) -> dict[str, dict[str, float]]:
    """The committed table in `text`'s generated block."""
    block = text[text.index(BEGIN):text.index(END)]
    pages: dict[str, dict[str, float]] = {}
    for style, body in re.findall(r'\["([^"]+)"\] = \{ ([^}]*) \}', block):
        for key, value in re.findall(r'(\["[^"]+"\]|[a-z]+) = ([0-9.]+)', body):
            pages.setdefault(style, {})[key.strip('[]"')] = float(value)
    return pages


def differences(old: dict[str, dict[str, float]], new: dict[str, dict[str, float]]) -> list[str]:
    """Each style and page whose committed luminance the art doesn't give (within TOLERANCE), or one missing."""
    out = []
    for style in sorted(set(old) | set(new)):
        for page in PAGES:
            a, b = old.get(style, {}).get(page), new.get(style, {}).get(page)
            if a is None or b is None:
                if a != b:
                    out.append(f"{style} {page}: committed {a}, the art gives {b}")
            elif abs(a - b) > TOLERANCE:
                out.append(f"{style} {page}: committed {a:.3f}, the art gives {b:.3f}")
    return out
