"""The one-time conversion of each addon's hand-written locale/enUS.lua into data/locale/enUS/*.toml (DATA-R114).

It is a script, not a hand edit, so that it can be run again: 1.0.1 changes English strings on main before the 1.1
branch merges, and the conversion is then dropped from the branch and re-run on the rebased tree. It does three things:

* runs each enUS.lua in Lua 5.1 (its locals, concatenations and helper calls are code, so only evaluating it gives the
  strings the game shows) and reads `ns.L` back as JSON;
* scans the file's text for the order of its keys and the comments above them, so the TOML keeps the grouping and the
  spec references that explain the strings;
* writes `data/locale/enUS/<id>.toml` and `locale.toml`, and copies each hand-written file to
  `spec/fixtures/enUS-handwritten/<Addon>.lua`, the reference `spec/locale_enus_spec.lua` compares the generated file's
  `ns.L` with.

The strings are kept exactly as they are (`%s`, `_ONE`/`_OTHER` pairs and all); rewriting them to `{fields}` is a later
change. The caller then runs the generator, which writes the six `enUS.lua` files.
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
import tomllib
from collections.abc import Sequence
from dataclasses import dataclass, field
from pathlib import Path

from pagle_data.cli import main as generate
from pagle_data.locale import ADDON_IDS, LOCALE_DIR, header_file, locale_file

FIXTURES = "spec/fixtures/enUS-handwritten"
GENERATED = "Generated by scripts/generate-data.py"
_NAME = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
_NUMBER = re.compile(r"0|[1-9][0-9]*")

# Lua 5.1 loads the file with a stub `Pagle` (a Module's CORE-R11 guard reads it) and writes `ns.L` as JSON: arrays for
# the sequences 1..n, objects for the rest (whole-number keys as digit strings), keys in order. A string key that
# reads as a whole number would be ambiguous with a number key, so the script refuses it.
LUA_DUMP = r"""
local path = arg[1]
Pagle = {}
local ns = {}
assert(loadfile(path))("addon", ns)
local L = ns.L
assert(type(L) == "table", path .. ": ns.L is not a table")

local function quote(s)
	return '"' .. s:gsub('[%c"\\]', function(c)
		if c == '"' then return '\\"' elseif c == "\\" then return "\\\\" elseif c == "\n" then return "\\n" end
		return ("\\u%04x"):format(c:byte())
	end) .. '"'
end

local function less(a, b)
	if type(a) == type(b) then return a < b end
	return type(a) == "number"
end

local function encode(v, where)
	if type(v) == "string" then return quote(v) end
	if type(v) ~= "table" then error(where .. ": a " .. type(v) .. " is not text, an array or a table") end
	local keys, ints = {}, 0
	for k in pairs(v) do
		keys[#keys + 1] = k
		if type(k) == "number" then ints = ints + 1 end
		if type(k) == "string" and k:match("^%d+$") then error(where .. ": the string key '" .. k .. "' reads as a number") end
		if type(k) ~= "number" and type(k) ~= "string" then error(where .. ": a key that is a " .. type(k)) end
	end
	if #keys == 0 then error(where .. ": an empty table") end
	table.sort(keys, less)
	local parts = {}
	if ints == #keys and #v == ints then
		for i = 1, ints do parts[i] = encode(v[i], where .. "[" .. i .. "]") end
		return "[" .. table.concat(parts, ",") .. "]"
	end
	for _, k in ipairs(keys) do
		parts[#parts + 1] = quote(tostring(k)) .. ":" .. encode(v[k], where .. "." .. tostring(k))
	end
	return "{" .. table.concat(parts, ",") .. "}"
end

io.write(encode(L, "ns.L"))
"""


class ConvertError(Exception):
    """The conversion cannot go on; the message says what to fix."""


type Json = str | list[Json] | dict[str, Json]


def evaluate(lua: Path, source: Path) -> dict[str, Json]:
    """The `ns.L` the Lua file at `source` builds, read back through JSON."""
    done = subprocess.run([str(lua), "-", str(source)], input=LUA_DUMP.encode(), capture_output=True, check=False)
    if done.returncode != 0:
        raise ConvertError(f"{source}: Lua could not build ns.L: {done.stderr.decode('utf-8', 'replace').strip()}")
    loaded = json.loads(done.stdout.decode("utf-8"))
    if not isinstance(loaded, dict):
        raise ConvertError(f"{source}: ns.L is not a table of keys")
    return loaded


@dataclass
class Scanned:
    """What the text of an enUS.lua says beyond the values: the comment above its table, and for each top-level key,
    in order, the comments that explain it."""

    header: list[str] = field(default_factory=list)
    keys: list[str] = field(default_factory=list)
    comments: dict[str, list[str]] = field(default_factory=dict)
    blank_before: set[str] = field(default_factory=set)
    footer: list[str] = field(default_factory=list)


def _header_comment(head: str) -> list[str]:
    """The first block of `--` lines after the guard of a Module (or at the top of Core's file)."""
    lines = head.splitlines()
    start = 0
    if lines and lines[0].startswith("if not Pagle"):
        start = next((index for index, line in enumerate(lines) if line == "end"), -1) + 1
    while start < len(lines) and not lines[start].strip():
        start += 1
    block: list[str] = []
    for line in lines[start:]:
        if not line.startswith("--"):
            break
        block.append(line[2:].rstrip())
    return block


def scan(text: str) -> Scanned:
    """The keys of `ns.L = { … }` in the order written, with the comments above each and where a blank line set a
    group apart. Strings and comments are skipped properly, so a brace or `--` inside a string does not count."""
    start = re.search(r"^ns\.L = \{", text, re.MULTILINE)
    if start is None:
        raise ConvertError("no `ns.L = {` at the start of a line")
    found = Scanned(header=_header_comment(text[: start.start()]))
    depth = 1
    i, length = start.end(), len(text)
    gap: list[str] = []
    gap_blank = False
    current: str | None = None
    inner: list[str] = []
    last: str | None = None
    newlines_since_end = 0

    def finish() -> None:
        nonlocal current, inner, last, newlines_since_end
        if current is not None:
            found.comments[current] = [*found.comments.get(current, []), *inner]
            last, current, inner, newlines_since_end = current, None, [], 0

    while i < length and depth > 0:
        char = text[i]
        if char in " \t\r":
            i += 1
        elif char == "\n":
            run = 1
            i += 1
            while i < length and text[i] in " \t\r\n":
                run += text[i] == "\n"
                i += 1
            if depth == 1 and current is None:
                newlines_since_end += run
                gap_blank = gap_blank or run >= 2
        elif text.startswith("--", i):
            long = re.match(r"--\[(=*)\[", text[i:])
            if long:
                close = text.find("]" + long.group(1) + "]", i)
                end = length if close < 0 else close + len(long.group(1)) + 2
                comment = text[i + 2 : end]
            else:
                end = text.find("\n", i)
                end = length if end < 0 else end
                comment = text[i + 2 : end]
            if depth > 1 or current is not None:
                inner.append(comment.rstrip())
            elif last is not None and newlines_since_end == 0:
                found.comments[last].append(comment.rstrip())
            else:
                gap.append(comment.rstrip())
            i = end
        elif char in "\"'":
            j = i + 1
            while j < length and text[j] != char:
                j += 2 if text[j] == "\\" else 1
            i = j + 1
        elif char == "[" and re.match(r"\[=*\[", text[i:]):
            level = re.match(r"\[(=*)\[", text[i:])
            assert level is not None
            close = text.find("]" + level.group(1) + "]", i)
            i = length if close < 0 else close + len(level.group(1)) + 2
        elif char == "{":
            depth += 1
            i += 1
        elif char == "}":
            depth -= 1
            i += 1
        elif char == "," and depth == 1:
            finish()
            i += 1
        elif depth == 1 and current is None and (name := _NAME.match(text, i)) and re.match(r"\s*=[^=]", text[name.end() :]):
            key = name.group(0)
            if key in found.keys:
                raise ConvertError(f"the key {key} is written twice; the later one wins in Lua, so remove the first")
            found.keys.append(key)
            found.comments[key] = list(gap)
            if gap_blank and len(found.keys) > 1:
                found.blank_before.add(key)
            gap, gap_blank = [], False
            current, inner = key, []
            i = name.end()
        else:
            i += 1
    finish()
    found.footer = gap
    return found


# --- writing TOML ----------------------------------------------------------------------------------------------------


def toml_string(value: str) -> str:
    """value as a TOML string: a literal string when it has backslashes and nothing that needs an escape (the texture
    paths read as they are), else a basic one."""
    if "\\" in value and "'" not in value and not any(ord(char) < 0x20 or ord(char) == 0x7F for char in value):
        return f"'{value}'"
    out = ['"']
    for char in value:
        if char == '"':
            out.append('\\"')
        elif char == "\\":
            out.append("\\\\")
        elif char == "\n":
            out.append("\\n")
        elif char == "\t":
            out.append("\\t")
        elif char == "\r":
            out.append("\\r")
        elif ord(char) < 0x20 or ord(char) == 0x7F:
            out.append(f"\\u{ord(char):04x}")
        else:
            out.append(char)
    out.append('"')
    return "".join(out)


def _key(name: str) -> str:
    return name if _NAME.fullmatch(name) or _NUMBER.fullmatch(name) else toml_string(name)


def _inline(value: Json) -> str:
    if isinstance(value, str):
        return toml_string(value)
    if isinstance(value, list):
        return "[" + ", ".join(_inline(item) for item in value) + "]"
    return "{ " + ", ".join(f"{_key(name)} = {_inline(item)}" for name, item in value.items()) + " }"


def entry_lines(key: str, value: Json) -> list[str]:
    """`key = value` as TOML lines: a string on one line, a table as one dotted line per string below it, an array on
    one line when it fits in 120 columns and else one element to a line."""
    if isinstance(value, str):
        return [f"{key} = {toml_string(value)}"]
    if isinstance(value, list):
        one = f"{key} = {_inline(value)}"
        if len(one) <= 120:
            return [one]
        return [f"{key} = [", *(f"\t{_inline(item)}," for item in value), "]"]
    lines: list[str] = []
    for name, item in value.items():
        lines += entry_lines(f"{key}.{_key(name)}", item)
    return lines


def _comment(text: str) -> str:
    return f"#{text}" if text else "#"


def toml_text(addon: str, data: dict[str, Json], scanned: Scanned) -> str:
    """One addon's English file: a header, then each key in the order it was written, under its comments."""
    out = [
        f"# {addon}'s interface text in English (CORE-R8, DATA-R114, ADR 0019). scripts/generate-data.py writes",
        f"# addons/{addon}/locale/enUS.lua from this file: edit this file and run the generator, never the Lua.",
        "#",
    ]
    if scanned.header:
        out += [_comment(line) for line in scanned.header]
        out.append("#")
    out += [
        "# Converted from the hand-written enUS.lua by scripts/convert-enus-locale.py: the strings are as they were,",
        "# `%s`, `_ONE`/`_OTHER` pairs and all. A key is `KEY = \"text\"`; an array is `KEY = [...]`; a table is dotted keys",
        "# (`KEY.sub = \"text\"`), a whole-number key being the Lua integer key (`CONTINENT_NAMES.0`), and a table of plural",
        "# categories is a counted string. The shape is in DATA-R114 (docs/spec/content-data.md).",
        "",
    ]
    for index, key in enumerate(scanned.keys):
        if key in scanned.blank_before:
            out.append("")
        out += [_comment(line) for line in scanned.comments.get(key, [])]
        out += entry_lines(key, data[key])
    if scanned.footer:
        out.append("")
        out += [_comment(line) for line in scanned.footer]
    return "\n".join(out) + "\n"


HEADER_TOML = """\
# English, the source of every Locale (DATA-R114). Its plural rule and separators are the text helper's built-in
# English (addons/Pagle/logic/Text.lua), and the generator checks that the two agree. English is always listed and
# falls back to nothing, so it has no `listed` and no `fallback`.

name = "English"
plural = "one_other"
decimal = "."
thousands = ","
"""


def convert(root: Path, lua: Path | None = None) -> list[str]:
    """Converts every addon's enUS.lua under root; returns the paths written. Raises ConvertError for a tree that is
    already converted or a file that cannot be."""
    interpreter = lua or root / ".tools" / "bin" / "lua"
    if not interpreter.exists():
        found = shutil.which("lua")
        if found is None:
            raise ConvertError(f"no Lua 5.1 at {interpreter}; run scripts/setup.sh")
        interpreter = Path(found)
    target = root / LOCALE_DIR / "enUS"
    if target.exists():
        raise ConvertError(f"{LOCALE_DIR}/enUS/ already exists; remove it (git rm -r) to convert again")
    sources = {addon: root / "addons" / addon / "locale" / "enUS.lua" for addon in ADDON_IDS}
    texts: dict[str, str] = {}
    for addon, path in sources.items():
        if not path.is_file():
            raise ConvertError(f"{path}: no hand-written enUS.lua to convert")
        texts[addon] = path.read_text(encoding="utf-8")
        if any(GENERATED in line for line in texts[addon].splitlines()[:8]):
            raise ConvertError(f"{path} is already generated; the conversion has been done")
    written: list[str] = []
    files: dict[Path, str] = {root / header_file("enUS"): HEADER_TOML}
    for addon, path in sources.items():
        data = evaluate(interpreter, path)
        scanned = scan(texts[addon])
        if set(scanned.keys) != set(data):
            odd = sorted(set(scanned.keys) ^ set(data))
            raise ConvertError(f"{path}: the keys read from the text and from Lua differ at {', '.join(odd)}")
        text = toml_text(addon, data, scanned)
        if tomllib.loads(text) != data:
            raise ConvertError(f"{path}: the TOML written does not read back as ns.L")
        files[root / locale_file("enUS", ADDON_IDS[addon])] = text
        files[root / FIXTURES / f"{addon}.lua"] = texts[addon]
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        written.append(str(path.relative_to(root)))
    return sorted(written)


PROG = "convert-enus-locale"


def main(argv: Sequence[str], root: Path) -> int:
    """Runs the command line on the repo at root; returns the exit code."""
    parser = argparse.ArgumentParser(
        prog="scripts/convert-enus-locale.py",
        description="Convert each addon's hand-written locale/enUS.lua into data/locale/enUS/*.toml (DATA-R114).",
    )
    parser.add_argument("--no-generate", action="store_true", help="write the TOML and the reference copies, not the Lua")
    args = parser.parse_args(argv)
    try:
        written = convert(root)
    except ConvertError as error:
        print(f"{PROG}: {error}", file=sys.stderr)
        return 1
    for path in written:
        print(f"{PROG}: wrote {path}")
    if args.no_generate:
        return 0
    return generate([], root)
