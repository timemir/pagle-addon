#!/usr/bin/env bash
# Writes spec/Pagle/fixtures/Signing.lua, the known answers the specs check Core's Base64, SHA-256 and RSA code
# against (PUSH-R2, PUSH-R11), from the files beside it in spec/Pagle/fixtures/signing/ and the pinned Wycheproof
# vectors in spec/Pagle/fixtures/wycheproof/. Everything in it comes from openssl, never from Pagle's own code:
#
#   - the test key and the Wycheproof key, as scripts/pushed-key.py prints them (n, rr, n0inv);
#   - openssl dgst -sha256 over prefixes of random-64k.bin (65536 bytes from openssl rand);
#   - openssl base64 -A over the 256 byte values in order;
#   - openssl dgst -sha256 -sign with test-only-private-key.pem over a few messages, each checked back with
#     openssl dgst -sha256 -verify. PKCS#1 v1.5 signing is deterministic, so a rerun writes the same file.
#
#   scripts/make-signing-fixtures.sh
#
# The private key is TEST ONLY and lives under spec/, which no release holds (scripts/package.sh zips addons/ only).
# Needs openssl (3.x or later; on macOS Homebrew's, not the system LibreSSL) and the pinned Python from
# scripts/setup.sh.
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
dir="$root/spec/Pagle/fixtures/signing"
wyche="$root/spec/Pagle/fixtures/wycheproof/rsa_signature_2048_sha256_test.json"
out="$root/spec/Pagle/fixtures/Signing.lua"
# shellcheck source=lib/tools.sh
source "$root/scripts/lib/tools.sh"
python="$(tools_dir "$root")/bin/python"
key="$dir/test-only-private-key.pem"
data="$dir/random-64k.bin"

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

hex() {
	od -An -tx1 -v | tr -d ' \n'
}

# The first $1 bytes of random-64k.bin (BSD head refuses -c 0).
prefix() {
	if (($1 > 0)); then head -c "$1" "$data"; fi
}

# The digest of the first $1 bytes of random-64k.bin, as lowercase hex.
digest() {
	prefix "$1" | openssl dgst -sha256 -binary | hex
}

# Signs stdin with the test key, checks the signature back, and prints it as hex.
sign() {
	cat >"$work/message"
	openssl dgst -sha256 -sign "$key" -out "$work/sig" "$work/message"
	openssl dgst -sha256 -verify "$dir/test-key-public.pem" -signature "$work/sig" "$work/message" >/dev/null
	hex <"$work/sig"
}

"$python" -I -c 'import json, sys; print(json.load(open(sys.argv[1]))["testGroups"][0]["publicKeyPem"])' \
	"$wyche" >"$work/wycheproof.pem"

{
	echo "-- Generated by scripts/make-signing-fixtures.sh from spec/Pagle/fixtures/signing/ and the pinned Wycheproof"
	echo "-- vectors; don't edit. Every value here came from openssl, never from Pagle's code. TEST ONLY: the test key"
	echo "-- signs these fixtures and nothing else."
	echo "return {"
	echo "	-- scripts/pushed-key.py over signing/test-key-public.pem, the test key's public half."
	"$python" "$root/scripts/pushed-key.py" "$dir/test-key-public.pem" testKey | sed 's/^\t\["testKey"\] =/\ttestKey =/'
	echo "	-- scripts/pushed-key.py over the publicKeyPem of the Wycheproof file's first test group (e = 65537)."
	"$python" "$root/scripts/pushed-key.py" "$work/wycheproof.pem" wycheproofKey |
		sed 's/^\t\["wycheproofKey"\] =/\twycheproofKey =/'
	echo "	-- openssl dgst -sha256 over the first [length] bytes of signing/random-64k.bin."
	echo "	prefixDigests = {"
	for length in $(seq 0 130) 447 448 1000 1023 1024 1025 4096 65535 65536; do
		echo "		[$length] = \"$(digest "$length")\","
	done
	echo "	},"
	echo "	-- openssl base64 -A over the 256 byte values, 0 to 255 in order."
	printf '\tallBytesBase64 = "%s",\n' "$("$python" -I -c 'import sys; sys.stdout.buffer.write(bytes(range(256)))' |
		openssl base64 -A)"
	echo "	-- openssl dgst -sha256 -sign signing/test-only-private-key.pem: each message as hex, or the first"
	echo "	-- [prefix] bytes of signing/random-64k.bin."
	echo "	signatures = {"
	for message in "" "abc" "1|1791731700|testKey|42|1792336500|{items={},}"; do
		printf '\t\t{ message = "%s", signature = "%s" },\n' \
			"$(printf '%s' "$message" | hex)" "$(printf '%s' "$message" | sign)"
	done
	for prefix in 4096 65536; do
		printf '\t\t{ prefix = %d, signature = "%s" },\n' "$prefix" "$(prefix "$prefix" | sign)"
	done
	echo "	},"
	echo "	-- The raw RSA public operation, s^65537 mod n under the test key, by openssl pkeyutl -verifyrecover with"
	echo "	-- rsa_padding_mode:none: 0, 1, 2, n - 2, n - 1, and values from SHA-256 of a counter, reduced mod n."
	echo "	raw = {"
	"$python" -I -c '
import hashlib, re, sys
n = int(re.search(r"n = \"([0-9a-f]+)\"", sys.stdin.read()).group(1), 16)
values = [0, 1, 2, n - 2, n - 1]
for i in range(12):
    wide = b"".join(hashlib.sha256(f"pagle-raw-{i}-{j}".encode()).digest() for j in range(8))
    values.append(int.from_bytes(wide, "big") % n)
for value in values:
    print(f"{value:0512x}")
' < <("$python" "$root/scripts/pushed-key.py" "$dir/test-key-public.pem" testKey) |
		while read -r s; do
			printf '%s' "$s" | "$python" -I -c 'import sys; sys.stdout.buffer.write(bytes.fromhex(sys.stdin.read()))' \
				>"$work/s"
			m=$(openssl pkeyutl -verifyrecover -pubin -inkey "$dir/test-key-public.pem" \
				-pkeyopt rsa_padding_mode:none -in "$work/s" | hex)
			printf '\t\t{ s = "%s", m = "%s" },\n' "$s" "$m"
		done
	echo "	},"
	echo "	-- Blocks for the message \"abc\", each signed raw by the test key (the raw private operation: openssl"
	echo "	-- pkeyutl -decrypt with rsa_padding_mode:none), so the RSA step is right and only the block differs from"
	echo "	-- RFC 8017 §9.2's EMSA-PKCS1-v1_5. \"exact\" is the right block, the same signature openssl dgst -sign makes;"
	echo "	-- every other one must fail."
	echo "	crafted = {"
	"$python" -I -c '
import hashlib
k = 256
digest = hashlib.sha256(b"abc").digest()
info256 = bytes.fromhex("3031300d060960864801650304020105000420")
t = info256 + digest
def block(t, ps_len=None, head=b"\x00\x01", fill=0xFF, sep=b"\x00", tail=b""):
    if ps_len is None:
        ps_len = k - len(head) - len(sep) - len(t) - len(tail)
    em = head + bytes([fill]) * ps_len + sep + t + tail
    assert len(em) == k, (len(em), ps_len)
    return em
def tweak(em, at, value):
    return em[:at] + bytes([value]) + em[at + 1:]
blocks = [
    ("exact", block(t)),
    ("block type 2", block(t, head=b"\x00\x02")),
    ("no leading zero byte", b"\x01" + block(t)[2:] + b"\x00"),
    ("a padding byte that is not FF", tweak(block(t), 100, 0xFE)),
    ("no zero byte after the padding", tweak(block(t), k - len(t) - 1, 0xFF)),
    ("eight bytes of padding and garbage after the digest", block(t, ps_len=8, tail=b"\x42" * (k - 11 - len(t)))),
    ("the digest of another message", block(info256 + hashlib.sha256(b"abd").digest())),
    ("a DigestInfo without its NULL", block(bytes.fromhex("302f300b0609608648016503040201") + b"\x04\x20" + digest)),
    ("SHA-1 DigestInfo", block(bytes.fromhex("3021300906052b0e03021a05000414") + hashlib.sha1(b"abc").digest())),
    ("SHA-512 OID over the SHA-256 digest", block(bytes.fromhex("3031300d060960864801650304020305000420") + digest)),
    ("a long-form DigestInfo length", block(bytes.fromhex("308131300d060960864801650304020105000420") + digest)),
    ("the bare digest, no DigestInfo", block(digest)),
]
for name, em in blocks:
    print(name + "\t" + em.hex())
' | while IFS=$'\t' read -r name em; do
		printf '%s' "$em" | "$python" -I -c 'import sys; sys.stdout.buffer.write(bytes.fromhex(sys.stdin.read()))' \
			>"$work/em"
		sig=$(openssl pkeyutl -decrypt -inkey "$key" -pkeyopt rsa_padding_mode:none -in "$work/em" | hex)
		printf '\t\t{ name = "%s", signature = "%s" },\n' "$name" "$sig"
	done
	echo "	},"
	echo "}"
} >"$work/Signing.lua"

mv "$work/Signing.lua" "$out"
echo "Wrote ${out#"$root"/}"
