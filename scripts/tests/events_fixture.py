def write_event(root: Path, file_id: str, text: str) -> None:
    path = root / event_file(file_id)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def write_tags(root: Path, text: str = TAGS) -> None:
    path = root / TAGS_TOML
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def write_tree(root: Path, events: dict[str, str] | None = None, areas: str = AREAS_TOML + SKILL_14) -> Path:
    """test_catch_lists.py's tree with DB2_ITEMS' qualities, the tag list and the given event files by file ID
    (SHALLOWS alone when none are given)."""
    write_areas_tree(root, areas)
    (root / "data" / "db2" / "items.csv").write_text(DB2_ITEMS, encoding="utf-8")
    write_tags(root)
    for file_id, text in ({"stv_shallows": SHALLOWS} if events is None else events).items():
        write_event(root, file_id, text)
    return root


def event(
    event_id: str,
    hunts: int = 3,
    *,
    zones: str = "[33]",
    tags: str = "[]",
    extra: str = "",
    hunt_body: str = "class = \"species.any\"\n",
) -> str:
    """An event file with the given number of plain Hunts, each <event_id>_<n> on species.any with tiers [5]."""
    text = f'[event]\nid = "{event_id}"\nzones = {zones}\ntags = {tags}\n{extra}name = "N"\nnote = "A note."\n'
    for index in range(1, hunts + 1):
        text += f'\n[[hunt]]\nid = "{event_id}_{index}"\n{hunt_body}tiers = [5]\nname = "H"\n'
    return text
