# The Catalogue.lua that EVENTS, LISTS, the fixture baseline's seed events and loot, windows_fixture's windows.toml,
# item_fixture's item layer and pools_fixture's pool type give (its records, ITEMS_JSON and ITEMS_LUA, are
# DATA-R77's; its pools, POOLS_JSON and POOLS_LUA, DATA-R43's), written by hand from DATA-R6, DATA-R62, DATA-R76,
# DATA-R79 (without windows, from M2) and the Contracts section: W, the window specs, emitted once before
# ns.catalogue, and each window pointing at its W entry. The seeds are
# test_windows.py's; event.301 is { events = { 301 } } (DATA-R37), and event 7, with no weekly rule, has no window.
# Its fingerprint (DATA-R70) is from `printf '%s' '<canonical JSON>' | sha256sum`, where the canonical JSON is
# {"aliases":{},"areas":{},"auras":[1265220,1280342],
#  "events":{"301":{"confirmed":false,"duration":120,"start":840,"weekday":1},"7":{}},
#  "fishingSpells":[7620,18248],<item_fixture.ITEMS_JSON>,<pools_fixture.POOLS_JSON>,<WINDOWS_JSON>}
EXPECTED = (
    """\
-- Generated by scripts/generate-data.py from data/baseline/, data/forever/, data/db2/, data/observed/. Do not edit by hand: edit data/ and run the generator.
-- GPL-3.0-or-later. Contains data derived from the VMaNGOS world database (see NOTICE).

---@class PagleNS
local ns = select(2, ...)

"""
    + W_LUA
    + """
ns.catalogue = {
\taliases = {},
\tareas = {},
\tauras = { 1265220, 1280342 },
\tevents = {
\t\t[7] = {},
\t\t[301] = { confirmed = false, duration = 120, start = 840, weekday = 1 },
\t},
\tfingerprint = "bfb01104ce7386af",
\tfishingSpells = { 7620, 18248 },
"""
    + ITEMS_LUA
    + POOLS_LUA
    + WINDOWS_LUA
    + "}\n"
)


def write_tree(root: Path, events: str = EVENTS, lists: str = LISTS) -> Path:
    forever = root / "data" / "forever"
    forever.mkdir(parents=True, exist_ok=True)
    (forever / "events.toml").write_text(events, encoding="utf-8")
    (forever / "lists.toml").write_text(lists, encoding="utf-8")
    (forever / "aliases.toml").write_text("", encoding="utf-8")  # test_aliases.py covers aliases
    write_windows(root)  # test_windows.py covers windows
    write_areas(root)  # test_catch_lists.py covers areas.toml
    write_baseline(root)  # test_generate_baseline.py covers the baseline layer
    write_observed(root)  # dev.toml with no facts; test_observed.py covers the layer
    write_item_layer(root)  # test_item_records.py covers the item layer
    write_pools(root)  # test_pools.py covers pool types
    # A DB2 layer with no areas or items (DATA-R11); test_db2_layer.py and test_db2_items.py cover them.
    db2 = root / "data" / "db2"
    db2.mkdir(parents=True, exist_ok=True)
    (db2 / "build.toml").write_text('build = 70338\nversion = "1.60.1"\nproducts = ["wow_classic_beta"]\n', encoding="utf-8")
    (db2 / "areas.csv").write_text("ID,ParentAreaID,ContinentID,AreaName_lang\n", encoding="utf-8")
    (db2 / "items.csv").write_text("ID,ClassID,SubclassID,OverallQualityID,Display_lang\n", encoding="utf-8")
    return root


def test_writes_the_catalogue_in_its_contract_shape(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    # DATA-R60: with no flag it rewrites every generated file (DATA-R75: Catalogue.lua). DATA-R79's shape, with
    # DATA-R6's header, keys ascending (DATA-R62), fishingSpells and auras ascending, events keyed by event ID, and
    # (from M2) the windows over the local W (Contracts, DATA-R35).
    code, _ = run(write_tree(tmp_path), capsys)
    assert code == 0
    assert (tmp_path / CATALOGUE).read_bytes() == EXPECTED.encode("utf-8")


def test_two_runs_give_byte_identical_files(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    # DATA-R62: the same data/ always gives byte-identical files.
    write_tree(tmp_path)
    run(tmp_path, capsys)
    first = (tmp_path / CATALOGUE).read_bytes()
    code, output = run(tmp_path, capsys)
    assert code == 0
    assert (tmp_path / CATALOGUE).read_bytes() == first
    assert "wrote" not in output


def test_check_passes_after_a_run(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    # DATA-R60, DATA-R61.
    run(write_tree(tmp_path), capsys)
    code, _ = run(tmp_path, capsys, "--check")
    assert code == 0


def test_check_fails_naming_the_file_once_data_changes_and_writes_nothing(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # DATA-R60: --check writes nothing and fails if any generated file would change; DATA-R61: a stale file fails.
    run(write_tree(tmp_path), capsys)
    before = (tmp_path / CATALOGUE).read_bytes()
    write_tree(tmp_path, lists="auras = [1280342]\nfishingSpells = [7620]\n")
    code, output = run(tmp_path, capsys, "--check")
    assert code == 1
    assert f"{CATALOGUE} is out of date" in output
    assert (tmp_path / CATALOGUE).read_bytes() == before


def test_check_fails_on_a_missing_generated_file_without_creating_it(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # DATA-R60: --check writes nothing.
    code, output = run(write_tree(tmp_path), capsys, "--check")
    assert code == 1
    assert CATALOGUE in output
    assert not (tmp_path / CATALOGUE).exists()


@pytest.mark.parametrize("mode", [[], ["--check"]])
def test_unknown_keys_and_wrong_types_fail_listing_every_problem_and_writing_nothing(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], mode: list[str]
) -> None:
    # DATA-R63: an unknown key or a wrong type in any TOML file under data/ fails, writing nothing and listing every
    # problem found, across both files.
    write_tree(
        tmp_path,
        events='colour = "red"\n[event.301]\nweekday = "Sunday"\nstart = 840\nduration = 120\nnote = 1\n',
        lists="auras = [1280341, true]\nfishingSpells = 7620\nspells = []\n",
    )
    (tmp_path / CATALOGUE).parent.mkdir(parents=True)
    (tmp_path / CATALOGUE).write_text("-- stale\n", encoding="utf-8")
    code, output = run(tmp_path, capsys, *mode)
    assert code == 1
    for problem in [
        "data/forever/events.toml: unknown key 'colour'",
        "data/forever/events.toml: event.301: unknown key 'note'",
        "data/forever/events.toml: event.301.weekday: expected an integer, got a string",
        "data/forever/lists.toml: unknown key 'spells'",
        "data/forever/lists.toml: auras[1]: expected an integer, got a boolean",
        "data/forever/lists.toml: fishingSpells: expected an array of IDs, got an integer",
        "6 problem(s) in data/; wrote nothing",
    ]:
        assert problem in output
    assert (tmp_path / CATALOGUE).read_text(encoding="utf-8") == "-- stale\n"


@pytest.mark.parametrize(
    ("events", "lists", "problem"),
    [
        # The Data section of docs/spec/content-data.md: weekday, start and duration are all three or none.
        (
            "[event.301]\nweekday = 1\n",
            LISTS,
            "event.301: a weekly rule sets weekday, start and duration together; missing start, duration",
        ),
        # DATA-R38: weekday 1 (Sunday) to 7, start a realm minute of the day, duration in minutes.
        ("[event.301]\nweekday = 8\nstart = 0\nduration = 1\n", LISTS, "weekday: expected an integer from 1 to 7"),
        ("[event.301]\nweekday = 1\nstart = 1440\nduration = 1\n", LISTS, "start: expected an integer from 0 to 1439"),
        ("[event.301]\nweekday = 1\nstart = 0\nduration = 0\n", LISTS, "duration: expected an integer at least 1"),
        ("[event.Extravaganza]\n", LISTS, "event.Extravaganza: expected a positive integer ID as the key"),
        ('event = "301"\n', LISTS, "events.toml: event: expected a table, got a string"),
        # The Data section: lists.toml's keys are auras and fishingSpells.
        (EVENTS, "auras = []\n", "lists.toml: missing key 'fishingSpells'"),
        (EVENTS, "auras = [7620, 7620]\nfishingSpells = []\n", "auras[1]: 7620 is listed twice"),
        (EVENTS, "auras = [0]\nfishingSpells = []\n", "auras[0]: expected an integer at least 1, got 0"),
        (EVENTS, "auras = [\n", "lists.toml: not valid TOML"),
    ],
)
def test_a_malformed_source_fails(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], events: str, lists: str, problem: str
) -> None:
    # DATA-R63: wrong TOML shapes and types fail and write nothing.
    code, output = run(write_tree(tmp_path, events, lists), capsys)
    assert code == 1
    assert problem in output
    assert not (tmp_path / CATALOGUE).exists()


def test_a_missing_source_file_fails(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    # DATA-R8, DATA-R10: the generator reads data/forever/events.toml and lists.toml.
    write_tree(tmp_path)
    (tmp_path / "data" / "forever" / "lists.toml").unlink()
    code, output = run(tmp_path, capsys)
    assert code == 1
    assert "data/forever/lists.toml: missing" in output
    assert not (tmp_path / CATALOGUE).exists()
