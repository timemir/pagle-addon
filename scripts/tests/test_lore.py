def test_lore_changes_neither_catalogue_lua_nor_the_fingerprint(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # DATA-R109, DATA-R70: lore is never in the catalogue or its fingerprint, so editing it changes only Lore.lua.
    root = write_lore_tree(tmp_path, checks=ON)
    first = emitted(root, capsys)
    catalogue = (root / CATALOGUE).read_bytes()
    (root / "data" / "lore" / "ledger.toml").write_text(LEDGER.replace("Groupers", "Big groupers"), encoding="utf-8")
    second = emitted(root, capsys)
    assert second == first.replace("Groupers", "Big groupers")
    assert (root / CATALOGUE).read_bytes() == catalogue
