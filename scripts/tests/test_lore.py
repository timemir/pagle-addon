ON = 'typicalLength = false\nlore = ["ledger"]\n'


def write_lore_tree(
    root: Path, ledger: str | None = LEDGER, manifest: str | None = MANIFEST, checks: str = OFF, **lore: str
) -> Path:
    """The item-records fixture tree with ITEMS and FAMILIES, plus data/lore/: ledger.toml and manifest.toml (each
    left out when None) and any other lore file by its name."""
    write_tree(root, ITEMS, families=FAMILIES, checks=checks)
    directory = root / "data" / "lore"
    directory.mkdir(parents=True, exist_ok=True)
    files = {"ledger.toml": ledger, "manifest.toml": manifest} | {f"{name}.toml": text for name, text in lore.items()}
    for name, text in files.items():
        if text is not None:
            (directory / name).write_text(text, encoding="utf-8")
    return root


def run(root: Path, capsys: pytest.CaptureFixture[str], *args: str) -> tuple[int, str]:
    code = main(list(args), root)
    out, err = capsys.readouterr()
    return code, out + err


def emitted(root: Path, capsys: pytest.CaptureFixture[str]) -> str:
    code, output = run(root, capsys)
    assert code == 0, output
    return (root / LORE_LUA).read_text(encoding="utf-8")


def fails(root: Path, capsys: pytest.CaptureFixture[str], *problems: str) -> str:
    """The generator fails naming every one of problems and writes nothing (DATA-R63); returns what it printed."""
    code, output = run(root, capsys)
    assert code == 1, output
    for problem in problems:
        assert problem in output
    assert not (root / LORE_LUA).exists()
    assert not (root / CATALOGUE).exists()
    return output


