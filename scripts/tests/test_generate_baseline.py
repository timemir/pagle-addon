CATALOGUE = "addons/Pagle/data/Catalogue.lua"
EVENTS = "[event.301]\nweekday = 1\nstart = 840\nduration = 120\n"
LISTS = "auras = [1280342]\nfishingSpells = [7620]\n"
BUILD = 'build = 70338\nversion = "1.60.1"\nproducts = ["wow_classic_beta"]\n'
AREAS = "ID,ParentAreaID,ContinentID,AreaName_lang\n"  # no areas: test_db2_layer.py covers them


def write_tree(root: Path) -> Path:
    forever = root / "data" / "forever"
    forever.mkdir(parents=True)
    (forever / "events.toml").write_text(EVENTS, encoding="utf-8")
    (forever / "lists.toml").write_text(LISTS, encoding="utf-8")
    (forever / "aliases.toml").write_text("", encoding="utf-8")  # test_aliases.py covers aliases
    write_windows(root)  # test_windows.py covers windows
    write_areas(root)  # test_catch_lists.py covers areas.toml
    db2 = root / "data" / "db2"
    db2.mkdir(parents=True)
    (db2 / "build.toml").write_text(BUILD, encoding="utf-8")
    (db2 / "areas.csv").write_text(AREAS, encoding="utf-8")
    (db2 / "items.csv").write_text("ID,ClassID,SubclassID,OverallQualityID,Display_lang\n", encoding="utf-8")
    write_baseline(root)
    write_item_layer(root)  # test_item_records.py covers the item layer
    write_pools(root)  # test_pools.py covers pool types
    write_hunts(root)  # test_hunts.py covers the Hunt list
    write_observed(root)  # dev.toml with no facts; test_observed.py covers the layer
    return root


def test_the_baseline_is_a_source_layer_and_no_chance_reaches_a_generated_file(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # DATA-R6: the header names the source layers, the baseline first (DATA-R8). DATA-R4: the baseline's chances
    # are never emitted. DATA-R16: the baseline's loot decides Noise (6358 is reachable only through reference loot);
    # DATA-R43: the pool type over 180248 catches its pool loot, 19807.
    code, _ = run(write_tree(tmp_path), capsys)
    assert code == 0
    text = (tmp_path / CATALOGUE).read_text(encoding="utf-8")
    assert text.startswith("-- Generated by scripts/generate-data.py from data/baseline/, data/forever/, data/db2/, data/observed/.")
    for chance in ("31.415", "27.18", "61.8", "14.14", "0.0271"):
        assert chance not in text
    assert "\t\t[6358] = { category = \"other\", legend = false, noise = true, pool = false, removed = false },\n" in text
    assert "\tpools = {\n\t\textravaganza = { 19807 },\n\t},\n" in text


@pytest.mark.parametrize("name", sorted(CSVS))
@pytest.mark.parametrize("mode", [[], ["--check"]])
def test_one_changed_byte_in_a_baseline_csv_fails_naming_the_file(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], name: str, mode: list[str]
) -> None:
    # DATA-R9: "The generator fails if any CSV's hash differs from source.toml"; DATA-R63: writing nothing.
    run(write_tree(tmp_path), capsys)
    before = (tmp_path / CATALOGUE).read_bytes()
    path = tmp_path / "data" / "baseline" / name
    data = bytearray(path.read_bytes())
    data[-2] ^= 1  # the last character before the final newline
    path.write_bytes(bytes(data))
    code, output = run(tmp_path, capsys, *mode)
    assert code == 1
    assert f"data/baseline/{name}: its SHA-256 differs from data/baseline/source.toml" in output
    assert (tmp_path / CATALOGUE).read_bytes() == before


def test_source_toml_problems_are_listed_together(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    # DATA-R63: an unknown key or a wrong type in any TOML file under data/; source.toml's keys are DATA-R9's
    # (tag, date, url, dumpSha256, [sha256] with one key per CSV).
    source = source_toml(SNAPSHOT, CSVS)
    source = source.replace("date = 2026-09-28", 'date = "2026-09-28"').replace('url = "', 'link = "')
    source = source.replace('[sha256]\n"area_loot.csv"', '[sha256]\n"areas.csv" = "00"\n"area_loot.csv"')
    source = source.replace('dumpSha256 = "abab', 'dumpSha256 = "ABAB')
    write_tree(tmp_path)
    write_baseline(tmp_path, source=source)
    code, output = run(tmp_path, capsys)
    assert code == 1
    for problem in [
        "data/baseline/source.toml: unknown key 'link'",
        "data/baseline/source.toml: missing key 'url'",
        "data/baseline/source.toml: date: expected a date, got a string",
        "data/baseline/source.toml: dumpSha256: expected 64 lowercase hex characters",
        "data/baseline/source.toml: sha256: unknown key 'areas.csv'",
    ]:
        assert problem in output
    assert not (tmp_path / CATALOGUE).exists()


def test_a_missing_or_unlisted_csv_fails(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    # DATA-R9: the baseline holds exactly its six CSVs, each hashed in source.toml.
    write_tree(tmp_path)
    baseline = tmp_path / "data" / "baseline"
    (baseline / "skill.csv").unlink()
    (baseline / "notes.csv").write_text("x\n", encoding="utf-8")
    code, output = run(tmp_path, capsys)
    assert code == 1
    assert "data/baseline/skill.csv: missing" in output
    assert "data/baseline/notes.csv: not a baseline file" in output


def test_a_csv_whose_columns_are_not_data_r9s_fails(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    # DATA-R9's columns, even when source.toml's hash matches the file.
    write_tree(tmp_path)
    write_baseline(tmp_path, {**CSVS, "skill.csv": "area,skill\n1,-70\n", "pools.csv": "entry,name,event\nx,y,\n"})
    code, output = run(tmp_path, capsys)
    assert code == 1
    assert "data/baseline/skill.csv: line 1: expected the columns area,skillBase" in output
    assert "data/baseline/pools.csv: line 2: entry: expected an integer, got 'x'" in output


@pytest.mark.parametrize("mode", [[], ["--check"]])
def test_a_loot_row_with_a_condition_is_ungated_and_printed_as_a_warning(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], mode: list[str]
) -> None:
    # DATA-R9: a condition that isn't a single event leaves `event` empty and "the generator treats such a row as
    # ungated and prints it as a warning"; DATA-R64: printed, not failing. The fixture's area 40 row has one; the
    # area 33 rows (an event, and a plain reference) don't.
    run(write_tree(tmp_path), capsys)
    code, output = run(tmp_path, capsys, *mode)
    assert code == 0
    warning = (
        "generate-data: warning: data/baseline/area_loot.csv: area 40 item 6303 has the condition"
        " and(event(45), not(event(47))), not a single event; it is treated as ungated"
    )
    assert warning in output
    assert output.count("treated as ungated") == 1
