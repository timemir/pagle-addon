"""Pagle_Hunts' lore (DATA-R105, DATA-R107, HNT-R130) over small fixture data/ trees: the Hunt and set text of
data/hunts/hunts.toml and the huntgood text of data/lore/hunts.toml, emitted into one Lore.lua, and the Hunts lore
check."""

from pathlib import Path

import pytest

from cli_fixture import run
from hunts_fixture import HUNTS
from test_hunts import write_tree as write_hunts_tree

HUNTS_LORE_LUA = "addons/Pagle_Hunts/data/Lore.lua"
OFF = "typicalLength = false\nlore = []\n"
ON = 'typicalLength = false\nlore = ["hunts"]\n'

# Hunts' own kind for its goods (HNT-R130, DATA-R106): two goods, each with a name and a description.
MANIFEST = '[hunts.huntgood]\nfields = ["name", "description"]\nids = ["hunts.cover.leather", "hunts.frame.none"]\n'
GOODS = """\
[huntgood."hunts.frame.none"]
name = "No Frame"
description = "Nothing around the lines."

[huntgood."hunts.cover.leather"]
name = "Leather"
description = "Plain brown."
"""

GUARDED = """\
-- Generated by scripts/generate-data.py from {sources}. Do not edit by hand: edit data/ and run the generator.
-- GPL-3.0-or-later. Contains data derived from the VMaNGOS world database (see NOTICE).

if not Pagle then -- luacheck: read globals Pagle (CORE-R11: the one read of Core outside adapter/)
\treturn
end

local L = select(2, ...).L

"""
# hunts_fixture's HUNTS text as Lore.lua writes it, by hand: hunt.<id>.name and .note, set.<id>.name, .title and
# .note (DATA-R105), sorted by byte (DATA-R62); the Hunts' lines, then the sets'.
HUNT_TEXT = """\
L["hunt.night_run.name"] = "Night Run"
L["hunt.oddity_at_dusk.name"] = "Oddity at Dusk"
L["hunt.oddity_at_dusk.note"] = "Anything odd."
"""
SET_TEXT = """\
L["set.camp_hours.name"] = "Camp Hours"
L["set.camp_hours.note"] = "Somewhere warm."
L["set.camp_hours.title"] = "the Hut Keeper"
L["set.round_the_clock.name"] = "Round the Clock"
L["set.round_the_clock.title"] = "the Clockwatcher"
"""


def write_tree(
    root: Path, hunts: str = HUNTS, goods: str | None = GOODS, manifest: str = MANIFEST, checks: str = OFF
) -> Path:
    """test_hunts.py's tree with hunts as data/hunts/hunts.toml, plus data/lore/manifest.toml, data/lore/hunts.toml
    (left out when None) and data/checks.toml."""
    write_hunts_tree(root, hunts)
    (root / "data" / "checks.toml").write_text(checks, encoding="utf-8")
    lore = root / "data" / "lore"
    lore.mkdir(parents=True, exist_ok=True)
    (lore / "manifest.toml").write_text(manifest, encoding="utf-8")
    if goods is not None:
        (lore / "hunts.toml").write_text(goods, encoding="utf-8")
    return root


def emitted(root: Path, capsys: pytest.CaptureFixture[str]) -> str:
    code, output = run(root, capsys)
    assert code == 0, output
    return (root / HUNTS_LORE_LUA).read_text(encoding="utf-8")


def test_hunt_and_set_text_is_emitted_into_pagle_hunts_lore_lua(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # DATA-R105: each Hunt's name and note and each set's name, title and note, from data/hunts/hunts.toml, as
    # hunt.<id>.<field> and set.<id>.<field>; DATA-R104: emitted with the check off, even with no lore file.
    root = write_tree(tmp_path, goods=None)
    assert emitted(root, capsys) == GUARDED.format(sources="data/hunts/hunts.toml") + HUNT_TEXT + SET_TEXT


def test_the_hunts_lore_check_passes_with_every_key_and_lore_lua_holds_both_sources(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # DATA-R66, DATA-R107: the hunts lore check is built in M5; with every good's name and description and every Hunt
    # and set text it passes. HNT-R130: the one Lore.lua holds the huntgood keys beside the Hunt and set text, all
    # sorted by byte (DATA-R62), so huntgood.* falls between hunt.* and set.*.
    goods = """\
L["huntgood.hunts.cover.leather.description"] = "Plain brown."
L["huntgood.hunts.cover.leather.name"] = "Leather"
L["huntgood.hunts.frame.none.description"] = "Nothing around the lines."
L["huntgood.hunts.frame.none.name"] = "No Frame"
"""
    sources = "data/hunts/hunts.toml, data/lore/hunts.toml"
    expected = GUARDED.format(sources=sources) + HUNT_TEXT + goods + SET_TEXT
    assert emitted(write_tree(tmp_path, checks=ON), capsys) == expected


def fails(root: Path, capsys: pytest.CaptureFixture[str], *problems: str) -> None:
    """The generator fails naming every one of problems and writes nothing (DATA-R63)."""
    code, output = run(root, capsys)
    assert code == 1, output
    for problem in problems:
        assert problem in output
    assert not (root / "addons").exists()


F = "data/hunts/hunts.toml: "
NAME_29 = "N" * 29  # one code point over a name's 28 (Tunables › Lore limits)
NONE_ALLOWED = "placeholder: { or } in a Hunt's or set's text, which allows none (DATA-R105, DATA-R107)"

# DATA-R105's checks on a Hunt's and a set's text with the Hunts lore check on: the list it breaks and the problem,
# naming hunts.toml and the key (None: it passes).
CASES = {
    "a 29-code-point Hunt name": (
        HUNTS.replace('name = "Night Run"', f'name = "{NAME_29}"'),
        F + "hunt.night_run.name: length: 29 code points, over name's limit of 28 (DATA-R107)",
    ),
    "a 28-code-point name of accented letters": (HUNTS.replace('name = "Night Run"', f'name = "{"é" * 28}"'), None),
    "a 33-code-point set title": (
        HUNTS.replace('title = "the Clockwatcher"', f'title = "{"t" * 33}"'),
        F + "set.round_the_clock.title: length: 33 code points, over title's limit of 32 (DATA-R107)",
    ),
    "a long note, which has no limit": (HUNTS.replace("Anything odd.", "Odd. " * 60), None),
    "a newline in a set note": (
        HUNTS.replace('note = "Somewhere warm."', 'note = "Somewhere\\nwarm."'),
        F + "set.camp_hours.note: newline: a line break (DATA-R107)",
    ),
    "{zone} in a Hunt note": (
        HUNTS.replace('note = "Anything odd."', 'note = "Anything odd in {zone}."'),
        F + "hunt.oddity_at_dusk.note: " + NONE_ALLOWED,
    ),
    "a lone brace in a set name": (
        HUNTS.replace('name = "Camp Hours"', 'name = "Camp Hours}"'),
        F + "set.camp_hours.name: " + NONE_ALLOWED,
    ),
    "an empty Hunt note": (
        HUNTS.replace('note = "Anything odd."', 'note = ""'),
        F + "hunt.oddity_at_dusk.note: missing: empty (DATA-R105, DATA-R107)",
    ),
    "a whitespace-only set title": (
        HUNTS.replace('title = "the Hut Keeper"', 'title = " "'),
        F + "set.camp_hours.title: missing: empty (DATA-R105, DATA-R107)",
    ),
}


@pytest.mark.parametrize(("hunts", "problem"), CASES.values(), ids=CASES.keys())
def test_the_hunts_lore_check_judges_hunt_and_set_text(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], hunts: str, problem: str | None
) -> None:
    # DATA-R105: the Hunts lore check adds the length (name 28, a set's title 32, a note none), newline and
    # placeholder checks (no { or } at all) and fails on an empty value; Tunables › Lore limits count code points.
    root = write_tree(tmp_path, hunts, checks=ON)
    if problem is None:
        code, output = run(root, capsys)
        assert code == 0, output
    else:
        fails(root, capsys, problem)


def test_with_the_check_off_bad_hunt_text_is_still_emitted_and_an_empty_note_left_out(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # DATA-R66: before the switch is on its check is skipped and the data is still emitted (DATA-R104); a key with no
    # text is left out, as a missing one is, so the board shows nothing for it (HNT-R1).
    hunts = HUNTS.replace('name = "Night Run"', f'name = "{NAME_29}"').replace('note = "Anything odd."', 'note = ""')
    text = emitted(write_tree(tmp_path, hunts), capsys)
    assert f'L["hunt.night_run.name"] = "{NAME_29}"\n' in text
    assert "hunt.oddity_at_dusk.note" not in text


def test_deleting_a_good_s_description_fails_as_missing_naming_the_key(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # DATA-R107's missing, for the hunts lore ID: the manifest lists the good (DATA-R106, HNT-R130).
    goods = GOODS.replace('description = "Plain brown."\n', "")
    fails(
        write_tree(tmp_path, goods=goods, checks=ON),
        capsys,
        "data/lore/hunts.toml: huntgood.hunts.cover.leather.description: missing: manifest.toml lists it (DATA-R106,"
        " DATA-R107)",
    )


def test_hunt_or_set_text_in_the_lore_file_is_an_orphan(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    # DATA-R100, DATA-R105: a Hunt's and a set's text stays in data/hunts/hunts.toml, never in data/lore/hunts.toml.
    goods = GOODS + '\n[set.camp_hours]\nname = "Camp Hours"\n'
    fails(
        write_tree(tmp_path, goods=goods, checks=ON),
        capsys,
        "data/lore/hunts.toml: set.camp_hours.name: orphan: a Hunt's and a set's text stays in data/hunts/hunts.toml"
        " (DATA-R100, DATA-R105, DATA-R107)",
    )
