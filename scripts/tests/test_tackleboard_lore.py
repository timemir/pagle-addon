"""Pagle_TackleBoard's lore (DATA-R106, DATA-R107, TKB-R130) over small fixture data/ trees: the fly, boardtitle and
boardgood text of data/lore/tackleboard.toml, emitted into Pagle_TackleBoard's Lore.lua, and the Tackle Board lore
check, on from M7."""

from pathlib import Path

import pytest

from cli_fixture import run
from test_lore import LEDGER, MANIFEST, fails, write_lore_tree

BOARD_LORE_LUA = "addons/Pagle_TackleBoard/data/Lore.lua"
ON = 'typicalLength = false\nlore = ["tackleboard"]\n'

# TKB-R130, DATA-R106: the Tackle Board's own kinds, fly (a name), boardtitle (a text) and boardgood (a name and a
# description). The Ledger owns title and Core owns good (DATA-R102), so the board's kinds have their own names.
BOARD_MANIFEST = (
    MANIFEST
    + '\n[tackleboard.fly]\nfields = ["name"]\nids = ["murloc_nymph", "deepwater_duchess"]\n'
    + '\n[tackleboard.boardtitle]\nfields = ["text"]\nids = ["tally_25", "flybox"]\n'
    + '\n[tackleboard.boardgood]\nfields = ["name", "description"]\nids = ["tackleboard.trackerframe.none"]\n'
)
BOARD = """\
[fly.murloc_nymph]
name = "Murloc Nymph"

[fly.deepwater_duchess]
name = "Deepwater Duchess"

[boardtitle.tally_25]
text = "Willing Hand"

[boardtitle.flybox]
text = "Fly-Tier"

[boardgood."tackleboard.trackerframe.none"]
name = "No Frame"
description = "The list on its own."
"""

# BOARD as Pagle_TackleBoard's Lore.lua writes it, by hand: Core's guard (CORE-R11), then the keys sorted by byte
# (DATA-R62).
BOARD_LUA = """\
-- Generated by scripts/generate-data.py from data/lore/tackleboard.toml. Do not edit by hand: edit data/ and run the\
 generator.
-- GPL-3.0-or-later. Contains data derived from the VMaNGOS world database (see NOTICE).

if not Pagle then -- luacheck: read globals Pagle (CORE-R11: the one read of Core outside adapter/)
\treturn
end

local L = select(2, ...).L

L["boardgood.tackleboard.trackerframe.none.description"] = "The list on its own."
L["boardgood.tackleboard.trackerframe.none.name"] = "No Frame"
L["boardtitle.flybox.text"] = "Fly-Tier"
L["boardtitle.tally_25.text"] = "Willing Hand"
L["fly.deepwater_duchess.name"] = "Deepwater Duchess"
L["fly.murloc_nymph.name"] = "Murloc Nymph"
"""
FILE = "data/lore/tackleboard.toml"


def write_tree(root: Path, board: str = BOARD, ledger: str = LEDGER, checks: str = ON) -> Path:
    return write_lore_tree(root, ledger, BOARD_MANIFEST, checks=checks, tackleboard=board)


def test_the_tackle_board_lore_check_is_built_and_passes_with_every_key(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # DATA-R107, for the tackleboard lore ID from M7 (DATA-R66): with every fly's name, title's text and good's name
    # and description it passes, and Pagle_TackleBoard's Lore.lua holds them (DATA-R104).
    root = write_tree(tmp_path)
    code, output = run(root, capsys)
    assert code == 0, output
    assert (root / BOARD_LORE_LUA).read_text(encoding="utf-8") == BOARD_LUA


def test_a_good_s_description_has_no_length_limit_and_a_title_may_be_32_code_points(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # Tunables › Lore limits: a good's description is unlimited, and a title's text is limited to 32 (not 28).
    board = BOARD.replace("The list on its own.", "The list on its own. " * 30).replace("Fly-Tier", "T" * 32)
    code, output = run(write_tree(tmp_path, board), capsys)
    assert code == 0, output


def test_deleting_a_fly_s_name_fails_as_missing_naming_the_key(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # DATA-R107's missing, for the tackleboard lore ID: the manifest lists the pattern (DATA-R106, TKB-R130).
    board = BOARD.replace('[fly.deepwater_duchess]\nname = "Deepwater Duchess"\n', "")
    fails(
        write_tree(tmp_path, board),
        capsys,
        f"{FILE}: fly.deepwater_duchess.name: missing: manifest.toml lists it (DATA-R106, DATA-R107)",
    )


CASES = {
    "29-code-point fly name": (
        ('name = "Murloc Nymph"', f'name = "{"M" * 29}"'),
        "fly.murloc_nymph.name: length: 29 code points, over name's limit of 28 (DATA-R107)",
    ),
    "33-code-point title": (
        ('text = "Willing Hand"', f'text = "{"W" * 33}"'),
        "boardtitle.tally_25.text: length: 33 code points, over text's limit of 32 (DATA-R107)",
    ),
    "29-code-point good name": (
        ('name = "No Frame"', f'name = "{"N" * 29}"'),
        "boardgood.tackleboard.trackerframe.none.name: length: 29 code points, over name's limit of 28 (DATA-R107)",
    ),
    "newline": (
        ('description = "The list on its own."', 'description = "The list\\non its own."'),
        "boardgood.tackleboard.trackerframe.none.description: newline: a line break (DATA-R107)",
    ),
    "brace": (
        ('name = "Murloc Nymph"', 'name = "Murloc {Nymph}"'),
        "fly.murloc_nymph.name: placeholder: { or } outside an allowed placeholder (manifest.toml allows none here)"
        " (DATA-R107, DATA-R108)",
    ),
}


@pytest.mark.parametrize(("edit", "problem"), CASES.values(), ids=CASES.keys())
def test_each_lore_check_fails_naming_the_key(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], edit: tuple[str, str], problem: str
) -> None:
    # DATA-R107's length (a name's 28 code points, a title's text 32, Tunables › Lore limits), newline and placeholder
    # checks: the manifest allows the Tackle Board's kinds no placeholder (DATA-R108).
    board = BOARD.replace(*edit)
    assert board != BOARD
    fails(write_tree(tmp_path, board), capsys, f"{FILE}: {problem}")


def test_a_fly_key_in_another_addon_s_file_is_an_orphan(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    # DATA-R102: fly is the Tackle Board's kind, so the Ledger's file can't hold it, even naming a listed pattern.
    ledger = LEDGER + '\n[fly.murloc_nymph]\nname = "Murloc Nymph"\n'
    fails(
        write_tree(tmp_path, ledger=ledger, checks='typicalLength = false\nlore = ["ledger", "tackleboard"]\n'),
        capsys,
        "data/lore/ledger.toml: fly.murloc_nymph.name: orphan: the kind fly is tackleboard's (DATA-R102, DATA-R107)",
    )
