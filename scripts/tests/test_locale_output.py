def test_a_fallback_locale_writes_only_what_it_gives(tmp_path: Path) -> None:
    mx = {"locale.toml": 'name = "Español de México"\nlisted = false\nfallback = "esES"\ndecimal = "."\n', "hunts.toml": ""}
    files = outputs(tmp_path, {"enUS": english(), "esES": spanish(), "esMX": mx})
    text = files["addons/Pagle_Hunts/locale/esMX.lua"]
