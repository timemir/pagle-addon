def test_base_names_the_branch_the_coverage_rule_compares_with(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch
) -> None:
    """A Locale marked listed with gaps fails only where the merge base with --base did not have it listed."""
    monkeypatch.delenv("GITHUB_BASE_REF", raising=False)

    def git(*args: str) -> None:
        identity = ["-c", "user.name=t", "-c", "user.email=t@t"]
        subprocess.run(["git", "-C", str(tmp_path), *identity, *args], check=True, capture_output=True)

    gapped = '[TITLE]\nvalue = "Pagle"\nen = "Pagle"\n'
    listed = SPANISH_HEADER.replace("listed = false", "listed = true")
    root = tree(tmp_path, {"enUS": english(), "esES": spanish(gapped, SPANISH_HEADER)})
    git("init", "-q", "-b", "main")
    git("add", "-A")
    git("commit", "-q", "-m", "esES unlisted")
    git("checkout", "-q", "-b", "topic")
    (root / "data" / "locale" / "esES" / "locale.toml").write_text(listed, encoding="utf-8")
    code, out = run(root, capsys, "--base", "main")
    assert code == 1 and "esES/locale.toml: listed: coverage:" in out
    code, out = run(root, capsys)  # no base known: the gap warns and the run goes on
    assert code == 0 and "warning: data/locale/esES/locale.toml: listed: coverage:" in out
    git("add", "-A")
    git("commit", "-q", "-m", "esES listed")
    git("checkout", "-q", "-b", "later")
    code, out = run(root, capsys, "--base", "topic")  # already listed at the merge base: the gap only warns
    assert code == 0 and "warning: data/locale/esES/locale.toml: listed: coverage:" in out
    code, out = run(root, capsys, "--base", "no-such-branch")
    assert code == 1 and "base for the coverage rule, no-such-branch" in out
    # The pull request's base from the environment: in a checkout that cannot find it, an error and not a warning...
    monkeypatch.setenv("GITHUB_BASE_REF", "gone")
    code, out = run(root, capsys)
    assert code == 1 and "base for the coverage rule, origin/gone" in out


