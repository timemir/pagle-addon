GUARD = (
    "if not Pagle then -- luacheck: read globals Pagle (CORE-R11: the one read of Core outside adapter/)\n"
    "\treturn\n"
    "end\n\n"
)


def layer_of(root: Path, trees: dict[str, dict[str, str]]) -> LocaleLayer:
    return checked(root, trees)[2]


def outputs(root: Path, trees: dict[str, dict[str, str]]) -> dict[str, str]:
    return locale_outputs(layer_of(root, trees))


def test_a_modules_enus_starts_with_the_guard_and_core_has_none(tmp_path: Path) -> None:
    files = outputs(tmp_path, {"enUS": english()})
    hunts = files["addons/Pagle_Hunts/locale/enUS.lua"]
    core = files["addons/Pagle/locale/enUS.lua"]
    assert hunts.startswith(GUARD)
    assert not core.startswith("if not Pagle")
    assert "Pagle" not in core.split("\n", 1)[0] or core.startswith("-- Generated")
    assert hunts == (
        GUARD
        + "-- Generated by scripts/generate-data.py from data/locale/enUS/hunts.toml. Do not edit by hand: edit data/ and"
        " run the generator.\n-- GPL-3.0-or-later.\n\n---@class PagleHuntsNS\nlocal ns = select(2, ...)\n\n"
        '---@class PagleHuntsStrings\nns.L = {\n\tHUNTS_ONLY = "Hunts",\n}\n'
    )


