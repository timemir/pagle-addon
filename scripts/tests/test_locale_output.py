def write_tree(root: Path) -> Path:
    """A valid data/ without lore or interface text (the lore layer is off)."""
    return write_items(root, ITEMS, families=FAMILIES, checks=OFF)


def tree(root: Path, trees: dict[str, dict[str, str]]) -> Path:
    write_tree(root)
    return write_locales(root, trees)


def test_check_fails_until_the_generator_has_run_and_then_passes(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    root = tree(tmp_path, {"enUS": english(), "esES": spanish()})
    code, out = run(root, capsys, "--check")
    assert code == 1
    assert "addons/Pagle/locale/enUS.lua is out of date" in out and "addons/Pagle_Hunts/locale/esES.lua is out of date" in out
    code, out = run(root, capsys)
    assert code == 0
    code, out = run(root, capsys, "--check")
    assert code == 0, out
    before = {path: path.read_bytes() for path in root.glob("addons/*/locale/*")}
    assert len(before) == 6 + 6 + 2  # enUS.lua and Locales.xml for each addon, esES.lua for the two it translates
    assert run(root, capsys)[0] == 0
    assert {path: path.read_bytes() for path in root.glob("addons/*/locale/*")} == before


