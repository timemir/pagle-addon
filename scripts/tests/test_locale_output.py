# CLDR's cardinal rules at sample counts: the integer part of the number alone (the helper hands over |count|).
VECTORS = {
    "other": {0: "other", 1: "other", 2: "other", 1.5: "other"},
    "one_other": {0: "other", 1: "one", 2: "other", 1.5: "other", 21: "other"},
    "one_many_other": {
        0: "other", 1: "one", 2: "other", 1.5: "other", 999999: "other", 1000000: "many", 3000000: "many", 1000000.5: "other",
    },  # fmt: skip
    "one_many_other_01": {0: "one", 0.5: "one", 1: "one", 1.5: "one", 2: "other", 1000000: "many", 2500000: "other"},
    "one_few_many_other": {
        0: "many", 1: "one", 2: "few", 4: "few", 5: "many", 10: "many", 11: "many", 12: "many", 14: "many", 21: "one",
        22: "few", 25: "many", 100: "many", 101: "one", 111: "many", 112: "many", 1.5: "other", 0.5: "other",
    },  # fmt: skip
}


def evaluate(name: str, counts: list[float]) -> list[str]:
    if not LUA.exists():
        pytest.skip("no .tools/bin/lua")
    script = f"local rule = {plural_lua(name, 0)}\nfor _, n in ipairs({{{','.join(repr(c) for c in counts)}}}) do print(rule(n)) end\n"
    done = subprocess.run([str(LUA), "-"], input=script, capture_output=True, text=True, check=True)
    return done.stdout.split()


def test_the_vectors_cover_every_rule() -> None:
    assert set(VECTORS) == set(RULES)


@pytest.mark.parametrize("name", sorted(VECTORS))
def test_each_rule_answers_cldr_categories_run_in_lua(name: str) -> None:
    counts = list(VECTORS[name])
    assert dict(zip(counts, evaluate(name, counts), strict=True)) == VECTORS[name]


@pytest.mark.parametrize("name", sorted(RULES))
def test_a_rule_answers_only_categories_it_declares(name: str) -> None:
    counts = [0, 0.5, 1, 1.5, 2, 3, 5, 11, 12, 21, 22, 100, 1000000]
    assert set(evaluate(name, counts)) <= set(RULES[name].categories)


def test_every_generated_file_compiles_under_lua_5_1(tmp_path: Path) -> None:
    if not LUAC.exists():
        pytest.skip("no .tools/lua/bin/luac")
    trees = {"enUS": english(), "esES": spanish(), "ruRU": {"locale.toml": RUSSIAN_HEADER, "core.toml": RUSSIAN_CORE}}
    for path, text in outputs(tmp_path, trees).items():
        if path.endswith(".lua"):
            target = tmp_path / path.replace("/", "_")
            target.write_text(text, encoding="utf-8")
            subprocess.run([str(LUAC), "-p", str(target)], check=True)


def test_a_generated_locale_registers_and_applies_through_the_registry(tmp_path: Path) -> None:
    """The whole path in Lua: Registry.lua, the generated esES.lua, then ApplyLocale writes the strings into ns.L and
    answers the record whose plural function the helper calls."""
    if not LUA.exists():
        pytest.skip("no .tools/bin/lua")
    files = outputs(tmp_path, {"enUS": english(), "esES": spanish()})
    (tmp_path / "enUS.lua").write_text(files["addons/Pagle/locale/enUS.lua"], encoding="utf-8")
    (tmp_path / "esES.lua").write_text(files["addons/Pagle/locale/esES.lua"], encoding="utf-8")
    script = f"""
local ns = {{}}
local function load(path) assert(loadfile(path))("Pagle", ns) end
load("{tmp_path}/enUS.lua")
load("{REPO}/addons/Pagle/locale/Registry.lua")
load("{tmp_path}/esES.lua")
assert(ns.L.TITLE == "Pagle" and ns.L.BANDS[1] == "Small")
local record, errors = ns.ApplyLocale("esES")
assert(#errors == 0, errors[1])
print(ns.L.BANDS[1], ns.L.FISH_COUNT.many, record.decimal, record.thousands, record.plural(1000000), ns.LocaleInfo("esES").name)
"""
    done = subprocess.run([str(LUA), "-"], input=script, capture_output=True, text=True, check=True)
    assert done.stdout.strip() == "Pequeño\t{count} de peces\t,\t.\tmany\tEspañol"


