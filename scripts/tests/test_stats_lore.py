"""Pagle_Stats' lore (DATA-R106, DATA-R107, STA-R88) over small fixture data/ trees: the statsgood text of
data/lore/stats.toml, emitted into Pagle_Stats' Lore.lua, and the Stats lore check, on from M6."""

from pathlib import Path

import pytest

from cli_fixture import run
from test_lore import LEDGER, MANIFEST, fails, write_lore_tree

STATS_LORE_LUA = "addons/Pagle_Stats/data/Lore.lua"
ON = 'typicalLength = false\nlore = ["stats"]\n'

# Stats' own kind for its goods (STA-R88, DATA-R106): two goods, each with a name and a description. Core owns good
# (DATA-R102), so Stats' kind is statsgood.
STATS_MANIFEST = (
    MANIFEST + '\n[stats.statsgood]\nfields = ["name", "description"]\nids = ["stats.frame.none", "stats.frame.brass"]\n'
)
GOODS = """\
[statsgood."stats.frame.none"]
name = "No Frame"
description = "Nothing around the figures."

[statsgood."stats.frame.brass"]
name = "Brass"
description = "A brass rim."
"""

# GOODS as Pagle_Stats' Lore.lua writes it, by hand: Core's guard (CORE-R11), then the keys sorted by byte (DATA-R62).
STATS_LUA = """\
-- Generated by scripts/generate-data.py from data/lore/stats.toml. Do not edit by hand: edit data/ and run the\
 generator.
-- GPL-3.0-or-later. Contains data derived from the VMaNGOS world database (see NOTICE).

if not Pagle then -- luacheck: read globals Pagle (CORE-R11: the one read of Core outside adapter/)
\treturn
end

local L = select(2, ...).L

L["statsgood.stats.frame.brass.description"] = "A brass rim."
L["statsgood.stats.frame.brass.name"] = "Brass"
L["statsgood.stats.frame.none.description"] = "Nothing around the figures."
L["statsgood.stats.frame.none.name"] = "No Frame"
"""
FILE = "data/lore/stats.toml"


def write_tree(root: Path, goods: str = GOODS, ledger: str = LEDGER, checks: str = ON) -> Path:
    return write_lore_tree(root, ledger, STATS_MANIFEST, checks=checks, stats=goods)


def test_the_stats_lore_check_is_built_and_passes_with_every_key(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # DATA-R107, for the stats lore ID from M6 (DATA-R66): with every good's name and description it passes, and
    # Pagle_Stats' Lore.lua holds them (DATA-R104).
    root = write_tree(tmp_path)
    code, output = run(root, capsys)
    assert code == 0, output
    assert (root / STATS_LORE_LUA).read_text(encoding="utf-8") == STATS_LUA


def test_a_description_has_no_length_limit(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    # Tunables › Lore limits: only a name is limited (28); a description has none, as for huntgood (HNT-R130).
    goods = GOODS.replace("A brass rim.", "A brass rim. " * 30)
    code, output = run(write_tree(tmp_path, goods), capsys)
    assert code == 0, output


def test_deleting_a_good_s_description_fails_as_missing_naming_the_key(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # DATA-R107's missing, for the stats lore ID: the manifest lists the good (DATA-R106, STA-R88).
    goods = GOODS.replace('description = "A brass rim."\n', "")
    fails(
        write_tree(tmp_path, goods),
        capsys,
        f"{FILE}: statsgood.stats.frame.brass.description: missing: manifest.toml lists it (DATA-R106, DATA-R107)",
    )


CASES = {
    "29-code-point name": (
        ('name = "Brass"', f'name = "{"B" * 29}"'),
        "statsgood.stats.frame.brass.name: length: 29 code points, over name's limit of 28 (DATA-R107)",
    ),
    "newline": (
        ('description = "A brass rim."', 'description = "A brass\\nrim."'),
        "statsgood.stats.frame.brass.description: newline: a line break (DATA-R107)",
    ),
    "brace": (
        ('description = "A brass rim."', 'description = "A brass {rim}."'),
        "statsgood.stats.frame.brass.description: placeholder: { or } outside an allowed placeholder (manifest.toml"
        " allows none here) (DATA-R107, DATA-R108)",
    ),
}


@pytest.mark.parametrize(("edit", "problem"), CASES.values(), ids=CASES.keys())
def test_each_lore_check_fails_naming_the_key(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], edit: tuple[str, str], problem: str
) -> None:
    # DATA-R107's length (a name's 28 code points, Tunables › Lore limits), newline and placeholder checks: the
    # manifest allows Stats' goods no placeholder (DATA-R108).
    goods = GOODS.replace(*edit)
    assert goods != GOODS
    fails(write_tree(tmp_path, goods), capsys, f"{FILE}: {problem}")


def test_a_statsgood_key_in_another_addon_s_file_is_an_orphan(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # DATA-R102: statsgood is Stats' kind, so the Ledger's file can't hold it, even naming a good the manifest lists.
    ledger = LEDGER + '\n[statsgood."stats.frame.none"]\nname = "No Frame"\n'
    fails(
        write_tree(tmp_path, ledger=ledger, checks='typicalLength = false\nlore = ["ledger", "stats"]\n'),
        capsys,
        "data/lore/ledger.toml: statsgood.stats.frame.none.name: orphan: the kind statsgood is stats' (DATA-R102,"
        " DATA-R107)",
    )
