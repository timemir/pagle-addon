def test_no_area_name_reaches_a_generated_file(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    # DATA-R3: names stay in the source CSV; the generator never emits them, in any form.
    run(write_tree(tmp_path), capsys)
    generated = (tmp_path / CATALOGUE).read_text(encoding="utf-8")
    for name in ["Quillwhistle", "Brackenmoor", "Upper", "Zephyrine", "Glade", "Shallows"]:
        assert name not in generated


def test_an_area_in_no_layer_is_unknown(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    # DATA-R13: a fact in no layer is unknown. Area 87 leaves areas.csv, so it leaves the catalogue; nothing else
    # names it. DATA-R2: identity facts (which areas exist, their parent and continent) come only from DB2.
    areas = AREAS.replace('87,12,0,"Brackenmoor, Upper"\n', "").replace("148,0,1,", "148,12,3,")
    run(write_tree(tmp_path, areas=areas), capsys)
    generated = (tmp_path / CATALOGUE).read_text(encoding="utf-8")
    assert "[87]" not in generated
    assert "[148] = { catches = {}, continent = 3, hasData = false, parent = 12, skillBaseConfirmed = false }," in (
        generated
    )


def test_where_and_when_facts_never_come_from_db2(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    # DATA-R2, DATA-R13: DB2 holds no where/when fact, so an areas.csv column that would carry one (a skill base, a
    # catch) is refused rather than read.
    areas = "ID,ParentAreaID,ContinentID,AreaName_lang,skillBase\n12,0,0,Quillwhistle Glade,25\n"
    code, output = run(write_tree(tmp_path, areas=areas), capsys)
    assert code == 1
    assert "data/db2/areas.csv: unknown column 'skillBase'" in output
