"""The DB2 layer as the generator reads it (DATA-R8 order 3, DATA-R11, DATA-R13) and the catalogue's areas it gives
(DATA-R25, DATA-R79), over small fixture data/ trees."""

from pathlib import Path

import pytest

from baseline_fixture import write_baseline
from pagle_data.cli import main
from windows_fixture import W_LUA, WINDOWS_LUA, write_windows

CATALOGUE = "addons/Pagle/data/Catalogue.lua"

EVENTS = "[event.301]\nweekday = 1\nstart = 840\nduration = 120\n"
LISTS = "auras = [1280342]\nfishingSpells = [7620]\n"

BUILD = 'build = 70338\nversion = "1.60.1"\nproducts = ["wow_classic_beta"]\n'

# Names chosen so that no other text in a generated file could hold them (DATA-R3's spec below).
AREAS = """\
ID,ParentAreaID,ContinentID,AreaName_lang
12,0,0,Quillwhistle Glade
87,12,0,"Brackenmoor, Upper"
148,0,1,Zephyrine Shallows
"""

# Catalogue.lua for the tree above, by hand from DATA-R6 (header), DATA-R25 and DATA-R79 (each area's parent,
# continent, hasData = false, skillBaseConfirmed = false, empty catches) and DATA-R62 (keys ascending), with
# windows_fixture's windows (DATA-R35). Its fingerprint (DATA-R70) is from
# `printf '%s' '<canonical JSON>' | sha256sum`, where the canonical JSON is
# {"aliases":{},"areas":{"12":{"catches":[],"continent":0,"hasData":false,"parent":0,"skillBaseConfirmed":false},
#  "148":{"catches":[],"continent":1,"hasData":false,"parent":0,"skillBaseConfirmed":false},
#  "87":{"catches":[],"continent":0,"hasData":false,"parent":12,"skillBaseConfirmed":false}},
#  "auras":[1280342],"events":{"301":{"confirmed":false,"duration":120,"start":840,"weekday":1}},
#  "fishingSpells":[7620],"items":{},"pools":{},<WINDOWS_JSON>}
EXPECTED = (
    """\
-- Generated by scripts/generate-data.py from data/baseline/, data/forever/, data/db2/. Do not edit by hand: edit data/ and run the generator.
-- GPL-3.0-or-later. Contains data derived from the VMaNGOS world database (see NOTICE).

---@class PagleNS
local ns = select(2, ...)

"""
    + W_LUA
    + """
ns.catalogue = {
\taliases = {},
\tareas = {
\t\t[12] = { catches = {}, continent = 0, hasData = false, parent = 0, skillBaseConfirmed = false },
\t\t[87] = { catches = {}, continent = 0, hasData = false, parent = 12, skillBaseConfirmed = false },
\t\t[148] = { catches = {}, continent = 1, hasData = false, parent = 0, skillBaseConfirmed = false },
\t},
\tauras = { 1280342 },
\tevents = {
\t\t[301] = { confirmed = false, duration = 120, start = 840, weekday = 1 },
\t},
\tfingerprint = "e8ef0e5bb93be260",
\tfishingSpells = { 7620 },
\titems = {},
\tpools = {},
"""
    + WINDOWS_LUA
    + "}\n"
)


def write_tree(root: Path, *, areas: str | None = AREAS, build: str | None = BUILD) -> Path:
    forever = root / "data" / "forever"
    forever.mkdir(parents=True, exist_ok=True)
    (forever / "events.toml").write_text(EVENTS, encoding="utf-8")
    (forever / "lists.toml").write_text(LISTS, encoding="utf-8")
    (forever / "aliases.toml").write_text("", encoding="utf-8")  # test_aliases.py covers aliases
    write_windows(root)  # test_windows.py covers windows
    write_baseline(root)  # test_generate_baseline.py covers the baseline layer
    db2 = root / "data" / "db2"
    db2.mkdir(parents=True, exist_ok=True)
    if areas is not None:
        (db2 / "areas.csv").write_text(areas, encoding="utf-8")
    if build is not None:
        (db2 / "build.toml").write_text(build, encoding="utf-8")
    return root


def run(root: Path, capsys: pytest.CaptureFixture[str], *args: str) -> tuple[int, str]:
    code = main(list(args), root)
    out, err = capsys.readouterr()
    return code, out + err


def test_every_areas_csv_row_is_a_catalogue_area(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    # DATA-R25: the catalogue's areas are every row of areas.csv, keyed by ID, with parent and continent; DATA-R79:
    # before M2 each has hasData = false, skillBaseConfirmed = false and empty catches. DATA-R6: the header names
    # the DB2 layer among the sources.
    code, output = run(write_tree(tmp_path), capsys)
    assert code == 0, output
    assert (tmp_path / CATALOGUE).read_text(encoding="utf-8") == EXPECTED


def test_a_bad_areas_csv_fails_listing_every_bad_row_and_writing_nothing(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    # DATA-R63 (as #56 asks of areas.csv): a non-integer ID or a row missing a column fails the generator, which
    # lists each bad row and writes nothing.
    areas = (
        "ID,ParentAreaID,ContinentID,AreaName_lang\n"
        "12,0,0,Quillwhistle Glade\n"
        "x12,0,0,Bad Id\n"
        "87,12\n"
        "88,12,zero,Bad Continent\n"
        "1.5,0,0,Fractional\n"
    )
    code, output = run(write_tree(tmp_path, areas=areas), capsys)
    assert code == 1
    for problem in [
        "data/db2/areas.csv: line 3: ID: expected a positive integer, got 'x12'",
        "data/db2/areas.csv: line 4: expected 4 fields, got 2: 87,12",
        "data/db2/areas.csv: line 5: ContinentID: expected an integer of 0 or more, got 'zero'",
        "data/db2/areas.csv: line 6: ID: expected a positive integer, got '1.5'",
        "4 problem(s) in data/; wrote nothing",
    ]:
        assert problem in output
    assert not (tmp_path / CATALOGUE).exists()


@pytest.mark.parametrize(
    ("areas", "problem"),
    [
        # DATA-R11: areas.csv has the four columns ID, ParentAreaID, ContinentID and the enUS name.
        ("ID,ParentAreaID,AreaName_lang\n12,0,Quillwhistle Glade\n", "areas.csv: missing column 'ContinentID'"),
        (
            "ID,ParentAreaID,ContinentID,AreaName_lang,ZoneMusic\n12,0,0,Quillwhistle Glade,3\n",
            "areas.csv: unknown column 'ZoneMusic'",
        ),
        ("", "areas.csv: empty: expected a header row"),
        ("ID,ParentAreaID,ContinentID,AreaName_lang\n0,0,0,Nowhere\n", "line 2: ID: expected a positive integer"),
        (
            "ID,ParentAreaID,ContinentID,AreaName_lang\n12,0,0,Quillwhistle Glade\n12,0,1,Again\n",
            "areas.csv: line 3: ID 12 is listed twice",
        ),
        ("ID,ParentAreaID,ContinentID,AreaName_lang\n12,-1,0,Below\n", "ParentAreaID: expected an integer of 0 or more"),
        ('ID,ParentAreaID,ContinentID,AreaName_lang\n12,0,0,"Open\n', "areas.csv: line 2: not a valid CSV row"),
    ],
)
def test_a_malformed_areas_csv_fails(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], areas: str, problem: str
) -> None:
    code, output = run(write_tree(tmp_path, areas=areas), capsys)
    assert code == 1
    assert problem in output
    assert not (tmp_path / CATALOGUE).exists()


