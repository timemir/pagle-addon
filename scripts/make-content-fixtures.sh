#!/usr/bin/env bash
# Writes spec/Pagle/fixtures/Content.lua, the signed Pagle_Content files the specs check Core's pushed-content reader
# against (PUSH-R2, PUSH-R10–R23): each a PagleContentData table that scripts/pushed-content.py writes over a payload
# in spec/Pagle/fixtures/content/, signed by openssl with the TEST ONLY key in spec/Pagle/fixtures/signing/, as
# keyId "testKey", seq 42, an hour before the specs' SERVER_TIME and expiring a week after it:
#
#   - good: content/good.txt, a huntEvent, a huntRun, a kind no Core knows and a huntRun of an unknown version;
#   - functionCall, singleQuote: content/function-call.txt and single-quote.txt, signed but outside the grammar;
#   - big: 65536 bytes exactly, the size cap (PUSH-R13), of huntRun items and a filler, for the timed run.
#
#   scripts/make-content-fixtures.sh
#
# PKCS#1 v1.5 signing is deterministic, so a rerun writes the same file. Specs register the test key's public half
# themselves; Core's shipped ns.PUSHED_KEYS never holds it. Needs openssl and the pinned Python from scripts/setup.sh.
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
fixtures="$root/spec/Pagle/fixtures"
out="$fixtures/Content.lua"
# shellcheck source=lib/tools.sh
source "$root/scripts/lib/tools.sh"
python="$(tools_dir "$root")/bin/python"
key="$fixtures/signing/test-only-private-key.pem"
# spec/support/addon.lua's SERVER_TIME.
server_time=1791731700
generated_at=$((server_time - 3600))
expires=$((server_time + 7 * 24 * 3600))

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# The big payload: huntRun items, then one filler item whose text pads the whole to 65536 bytes.
"$python" -I -c '
import sys
cap = 65536
head, tail = b"{items={\n", b"},}\n"
runs = []
start = 1791720000
for i in range(700):
    runs.append(b"{kind=\"huntRun\",v=1,event=\"p_test_event_%04d\",start=%d,[\"end\"]=%d,},\n" % (i, start + i * 3600, start + i * 3600 + 86400))
body = b"".join(runs)
filler_open, filler_close = b"{kind=\"filler\",v=1,text=\"", b"\",},\n"
pad = cap - len(head) - len(body) - len(filler_open) - len(filler_close) - len(tail)
assert pad > 0, pad
payload = head + body + filler_open + b"x" * pad + filler_close + tail
assert len(payload) == cap
sys.stdout.buffer.write(payload)
' >"$work/big.txt"

# One fixture: its name and the payload file, as a PagleContentData table.
entry() {
	printf '\t%s = %s,\n' "$1" "$("$python" -I "$root/scripts/pushed-content.py" "$2" --key-id testKey --seq 42 \
		--generated-at "$generated_at" --expires "$expires" --sign "$key" --table | sed '2,$s/^/\t/')"
}

{
	echo "-- Generated by scripts/make-content-fixtures.sh from spec/Pagle/fixtures/content/; don't edit. TEST ONLY:"
	echo "-- signed with the test key in spec/Pagle/fixtures/signing/, which Core's shipped keys never hold."
	echo "return {"
	echo "	generatedAt = $generated_at,"
	echo "	expires = $expires,"
	echo "	seq = 42,"
	entry good "$fixtures/content/good.txt"
	entry functionCall "$fixtures/content/function-call.txt"
	entry singleQuote "$fixtures/content/single-quote.txt"
	entry big "$work/big.txt"
	echo "}"
} >"$work/Content.lua"

mv "$work/Content.lua" "$out"
echo "Wrote ${out#"$root"/}"
