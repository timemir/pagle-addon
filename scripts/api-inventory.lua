-- Writes the WoW API inventory into the addon (#261): every name in .luacheckrc's stds.wow and stds.wow_variables,
-- dotted through its fields ("C_Weather.GetCurrentWeather"), sorted, into addons/Pagle/data/ApiInventory.lua as
-- ns.API_INVENTORY. `/pagle dev probe` checks each name on the client it runs on (launch re-verification check 11,
-- roadmap.md), so the inventory ships in the zip and the probe needs no repo. A field Pagle itself writes
-- (`read_only = false`, such as SlashCmdList.PAGLE) is left out: it's Pagle's, not the client's.
--
--   lua scripts/api-inventory.lua <.luacheckrc> <ApiInventory.lua>            write it
--   lua scripts/api-inventory.lua --check <.luacheckrc> <ApiInventory.lua>    fail while it's stale
--
-- The api stage of scripts/check.sh runs --check. Exits 2 on a usage error, 1 when --check finds the file stale.

local USAGE = "usage: lua scripts/api-inventory.lua [--check] <.luacheckrc> <ApiInventory.lua>\n"

-- The names a luacheck read_globals table declares: strings, and keys whose fields nest further. A field Pagle
-- writes is left out (scripts/api-presence.lua reads the same tables, and checks those too).
local function declared(globals, prefix, out)
	for key, value in pairs(globals or {}) do
		if type(key) == "number" then
			out[#out + 1] = prefix .. value
		elseif not (type(value) == "table" and value.read_only == false) then
			out[#out + 1] = prefix .. key
			if type(value) == "table" and value.fields then
				declared(value.fields, prefix .. key .. ".", out)
			end
		end
	end
	return out
end

-- The generated file's text: one name a line, as StyLua lays out a long table.
local function generate(names)
	local lines = {
		"-- Generated by scripts/api-inventory.lua from .luacheckrc's stds.wow and stds.wow_variables. Do not edit by"
			.. " hand:",
		"-- edit .luacheckrc and run lua scripts/api-inventory.lua .luacheckrc addons/Pagle/data/ApiInventory.lua.",
		"",
		"---@class PagleNS",
		"local ns = select(2, ...)",
		"",
		"--- Every WoW API name Pagle inventories, dotted through its fields, sorted: `/pagle dev probe` checks each on the",
		"--- client it runs on (launch re-verification check 11, #261).",
		"---@type string[]",
		"ns.API_INVENTORY = {",
	}
	for _, name in ipairs(names) do
		lines[#lines + 1] = ('\t"%s",'):format(name)
	end
	lines[#lines + 1] = "}"
	return table.concat(lines, "\n") .. "\n"
end

local function main(args)
	local check = args[1] == "--check"
	local configPath, outPath = args[check and 2 or 1], args[check and 3 or 2]
	if not configPath or not outPath then
		io.stderr:write(USAGE)
		return 2
	end
	-- luacheck runs its config with the standard library in reach, and so does this.
	local chunk = assert(loadfile(configPath))
	local config = setmetatable({ stds = {}, files = {} }, { __index = _G })
	setfenv(chunk, config)
	chunk()
	local names = {}
	for _, std in ipairs({ "wow", "wow_variables" }) do
		declared(config.stds[std] and config.stds[std].read_globals, "", names)
	end
	table.sort(names)
	local text = generate(names)

	if check then
		local file = io.open(outPath, "rb")
		local current = file and file:read("*a")
		if file then
			file:close()
		end
		if current ~= text then
			io.stderr:write(
				("api-inventory: %s is stale; run lua scripts/api-inventory.lua %s %s\n"):format(
					outPath,
					configPath,
					outPath
				)
			)
			return 1
		end
		return 0
	end
	local file = assert(io.open(outPath, "wb"))
	file:write(text)
	file:close()
	return 0
end

os.exit(main(arg))
