-- The conversion of the hand-written locale/enUS.lua files to data/locale/enUS/*.toml (DATA-R114, #517): the generated
-- enUS.lua of each addon builds the same `ns.L` the hand-written file built, key for key and value for value, tables
-- (GUIDE_COUNT_WORDS, RARITY_NAMES, CONTINENT_NAMES …) and whole-number keys included. The hand-written files are kept
-- as the reference, copied by scripts/convert-enus-locale.py to spec/fixtures/enUS-handwritten/<Addon>.lua at the
-- moment of the conversion; that run is repeatable, so the reference is the English of the tree it ran on.
--
-- This spec proves the conversion and nothing more. It is temporary by design: #519 rewrites the English strings to
-- `{fields}` on purpose, which makes the tables differ, and removes this spec and the reference copies in the same
-- change. Until then it fails on any English edit made to the generated file or the TOML without the reference.

local ADDONS = { "Pagle", "Pagle_Hunts", "Pagle_Ledger", "Pagle_QoL", "Pagle_Stats", "Pagle_TackleBoard" }
local REFERENCE = "spec/fixtures/enUS-handwritten/"

---@param path string
---@return boolean
local function exists(path)
	---@diagnostic disable-next-line: undefined-global -- busted runs on stock Lua 5.1; the WoW client has no io
	local file = io.open(path, "rb")
	if file then
		file:close()
	end
	return file ~= nil
end

-- The `ns.L` a locale file builds when it loads alone: a fresh namespace, and a stub `Pagle` for a Module's CORE-R11 guard.
---@param path string
---@return table
local function build(path)
	local ns = {}
	local saved = rawget(_G, "Pagle")
	rawset(_G, "Pagle", {})
	---@diagnostic disable-next-line: undefined-global -- busted runs on stock Lua 5.1; the WoW client has no loadfile
	local chunk = assert(loadfile(path))
	local ok, err = pcall(chunk, "addon", ns)
	rawset(_G, "Pagle", saved)
	assert(ok, err)
	return ns.L
end

describe("the generated enUS.lua of each addon (DATA-R114)", function()
	for _, addon in ipairs(ADDONS) do
		local title = addon .. " builds the ns.L the hand-written file built"
		if exists(REFERENCE .. addon .. ".lua") then
			it(title, function()
				local before = build(REFERENCE .. addon .. ".lua")
				local after = build("addons/" .. addon .. "/locale/enUS.lua")

				assert.is_table(after)
				assert.are.same(before, after)
			end)
		elseif exists("data/locale/enUS/locale.toml") then
			-- Converted, but the reference copy is gone: that must not pass quietly.
			it(title, function()
				error("no " .. REFERENCE .. addon .. ".lua: run scripts/convert-enus-locale.py again")
			end)
		else
			-- No reference copy: the conversion has not run on this tree.
			pending(title, function() end)
		end
	end

	it("is generated, so its header says so and a Module's starts with the CORE-R11 guard", function()
		for _, addon in ipairs(ADDONS) do
			local text = readFile("addons/" .. addon .. "/locale/enUS.lua")
			if text:find("Generated by scripts/generate-data.py", 1, true) then
				if addon ~= "Pagle" then
					assert.are.equal("if not Pagle then", text:sub(1, 17), addon)
				end
				assert.is_true(text:find("data/locale/enUS/", 1, true) ~= nil)
			end
		end
	end)
end)
